#!/usr/bin/env python3
"""Enroll every measured capability into the one registry the brain dispatches from, and *prove the
edge by executing it* before writing a single predicate.

WHAT THIS DOES
--------------
For each row of `canonical/capabilities/true/TRUE_CAPABILITY_LEDGER_V1.json` (the only capability
class in this repo measured under its own law — fresh instances, independent oracles, mutation
tested):

1. write a thin bound-capability adapter `canonical/runtime/bound_capabilities/truecap_<slug>.py`
   exposing the one envelope the other 146 adapters use (`run(args, root) -> dict`, `RuntimeError(CODE)`
   to fail closed). Adapters contain **no capability logic** — they forward to the measured entry point.
2. **execute** the composed pair generator -> solver on fresh instances, run each declared oracle
   against the real output, and record the result with digests in
   `canonical/capabilities/COMPOSITION_EDGES_V1.json`. Instance #0 is written to
   `canonical/capabilities/true/instances/<slug>.json` because a capability that can only be run with
   an in-memory dict cannot be re-run by anyone else: `capability_receipt_lane_v1` builds its probe
   args from the row's `action_template`, and a placeholder ending in `_path` is the only form the
   lane can hand to an adapter without inventing input.
3. derive the registry row from that execution: `result_fields` and `provides` are the keys the
   adapter *actually returned*; `requires` is empty because the input is a committed fixture rather
   than another capability's output; `limitations` come from the spec's
   `scope_limits`; `source` binds spec + receipt + the solver blob that was measured.
4. hand the row to the tree's own promotion queue: one
   `canonical/astra_runtime/pending_bindings/TRUECAP-ENROLL-<slug>__<fp>.json` per capability, shaped
   exactly like the rows `auto_pypi_library_acquisition.py` enqueues (`registry_entry`,
   `verification_fixture`, `verification_mission_id`, `verification_result_path`,
   `status: PENDING_INDEPENDENT_VERIFICATION`).

WHY A PENDING BINDING AND NOT A REGISTRY ROW
--------------------------------------------
`load_verified_registry` reads **four** sources (measured: live 154 rows, snapshot 146, extended 2,310,
receipt projection 305 entries; 447 rows admitted today) and admits a new capability only through
`_receipt_admits`: a producer receipt for the adapter at its content hash **and** an independent
verification record re-run by a different identity with a platform-attested `github_run_id`. Minting
either of those here is the SESSION_E0A256F8 failure mode this repo already fixed ("produced 464
self-verified receipts"), and AGENTS.md rule 4 says verification means someone else ran it. So this
tool writes no registry row at all -- it writes the adapter, the fixture, the measured edge, and the
queue entry the existing verifier consumes. What is claimed: the composition edge executes and every
declared oracle passes on fresh instances. What is not: any status.

`--check` re-derives everything and fails on drift, so the row cannot later disagree with the code.

Model calls: 0. Network: 0. Cost: $0.00.
"""
