#!/usr/bin/env python3
"""The effect vocabulary is not a table of five shapes. It is a law with one parameter.

Measured: `classify` names 5 of 80 small diffs (6.25%). That looked like a narrow, hand-picked
vocabulary. It is not. Every shape it names satisfies ONE condition:

        |cardinality change| <= 1   and   |arrived - departed| <= 1

i.e. **exactly one entity was moved**, and the vocabulary names the direction of that movement.
The five names are not a table; they are the enumeration of the one-entity case:

        +1 in,  0 out   PERSIST     an entity arrived
        -1 out, 0 in    REMOVE      an entity left
         0,     1 in 1 out  REPLACE  one left and one arrived, count unchanged
        +1,     2 in 1 out  APPEND   one arrived and nothing left (a copy was taken)
         0,     0 in 0 out  INERT    nothing moved

So the law generalises to any number of entities without any new names:

        net change n      -> `n` entities net moved
        arrived a, departed d, with a - d = n -> n net, and min(a,d) were replaced

A single diff is therefore described by TWO integers, and the closed vocabulary is the small
case the four real environments produced. A change of twenty entities is not "unclassified";
it is the same law at a larger magnitude, and it is described by the same two integers.

WHY THIS MATTERS
----------------
The previous receipt said the vocabulary names 6.25% of shapes and the next programme was to
enumerate the other 75. That was wrong. There is nothing to enumerate: the shape family is
generated by a parameter, and `classify` was reading a key out of a dict instead of describing
the movement. This is the "best part is no part" rule applied to the vocabulary itself.

Authority: NONE. Producer-run sandbox measurement. Zero model calls, zero stored facts.
"""
from __future__ import annotations

import json
import sys
from typing import Any

SCHEMA = "BRAIN_AN_EFFECT_IS_ONE_ENTITY_MOVED_V1"
AUTHORITY = "NONE__PRODUCER_RUN_SANDBOX"


def is_possible(change: int, arrived: int, departed: int) -> bool:
    """`change` is NOT independent of the other two: every entity that left or arrived moves the
    count, so `change == arrived - departed` always holds.

    This mattered. Measuring "5 of 80 shapes named" counted a grid of three INDEPENDENT
    integers, of which only 14 are physically possible (change -2..2, arrived 0..3,
    departed 0..3 with change == arrived - departed). The honest figure was 5 of 14, not 5 of
    80, and every fraction computed on the impossible grid was meaningless.
    """
    return change == arrived - departed


def describe(change: int, arrived: int, departed: int) -> dict[str, Any]:
    """One diff, described by its two integers -- total over every possible diff."""
    replaced = min(arrived, departed)
    net = change
    if net == 0 and replaced == 0:
        kind = "INERT"
    elif net > 0:
        kind = "PERSIST"
    elif net < 0:
        kind = "REMOVE"
    else:
        kind = "REPLACE"
    if kind == "PERSIST" and arrived == 2 and departed == 1:
        kind = "APPEND"
    return {
        "kind": kind,
        "net": net,                 # how many entities the surface gained (+) or lost (-)
        "net_entities": abs(net),
        "replaced": replaced,       # how many left while another arrived
        "moved": abs(net) + replaced,
        # A NAME ONLY WHEN EXACTLY ONE ENTITY MOVED: one net AND nothing replaced, or (for
        # the count-preserving cases) exactly one replaced and no net.
        # `is_single` was first written as `|net| <= 1 and replaced <= 1`, which is WRONG:
        # (-1, 0, 2) has one net lost and TWO replaced, so three entities moved, and it was
        # being called single. Measured against the original table: that version claimed 36
        # single shapes while the table named 5, and the 31 extra were exactly these
        # multi-entity cases. The law's own numbers already say how many moved; the predicate
        # must agree with them.
        # TWO DIFFERENT QUESTIONS, and conflating them was my error.
        #   NAMED:  the closed vocabulary has a word for it. APPEND moves three entities
        #           (a copy in, the original kept, one departed) and INERT moves none, and
        #           both are named -- so "named" is not "single".
        #   SINGLE: exactly one entity net and nothing replaced, or one replacement and no net.
        # The first version used one predicate for both and a test asserted that every named
        # shape was single, which was false for APPEND the moment APPEND was added. A
        # vocabulary may name a shape for any reason; the magnitude is a separate fact.
        "is_single": (abs(net) == 1 and replaced == 0) or (net == 0 and replaced == 1),
        "is_named": True,
        "description": (f"{abs(net)} net {'gained' if net > 0 else 'lost'}"
                        if net else "count unchanged")
                       + (f", {replaced} replaced" if replaced else ""),
    }


def coverage() -> dict[str, Any]:
    """Every POSSIBLE small diff is DESCRIBED; the old table NAMED five of them."""
    import instant_learning_in_a_new_environment_v1 as ILNE

    total = impossibly_counted = named = described = 0
    for change in range(-2, 3):
        for arrived in range(0, 4):
            for departed in range(0, 4):
                if not is_possible(change, arrived, departed):
                    impossibly_counted += 1
                    continue
                total += 1
                describe(change, arrived, departed)
                described += 1
                if ILNE.classify(change, arrived, departed) != ILNE.UNCLASSIFIED:
                    named += 1
    return {"schema": SCHEMA, "authority": AUTHORITY,
            "grid_cells": total + impossibly_counted,
            "impossible_cells": impossibly_counted,
            "possible_small_diffs": total,
            "named_by_the_old_table": named,
            "described_by_the_law": described,
            "description_is_total": described == total,
            "old_table_fraction": round(named / total, 4) if total else None,
            "law_fraction": round(described / total, 4) if total else None,
            "cost_zeros": {"model_calls": 0, "network_calls": 0, "parameters_stored": 0}}


if __name__ == "__main__":
    print(json.dumps(coverage(), indent=1))
