from typing import Any, Sequence

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

SCHEMA = "BRAIN_AN_EFFECT_NOT_A_DESCRIPTION_V1"
AUTHORITY = "NONE__PRODUCER_RUN_SANDBOX"

DECLARED: dict[str, str] = {
    "E1": "every plan is instantiated from the program's own usage line plus its own rendered vocabulary; no example invocation is supplied anywhere",
    "E2": "the amnesiac control holds: each plan is produced in a fresh subprocess given only the signature, the vocabulary and the goal",
    "E3": "an effect is claimed only when the output file exists, is non-empty, matches the formatter's documented envelope, and is byte-identical on a repeat run",
    "E4": "a plan that produces no effect is reported as NO_EFFECT, never retried into a success by hand",
    "E5": "at least one goal must be reachable by a machine-derived plan AND be unreachable by the follower's flag knowledge alone, or the capability claim is not made",
    "E6": "zero model calls, zero stored parameters, no network, no borrowed examples",
}

