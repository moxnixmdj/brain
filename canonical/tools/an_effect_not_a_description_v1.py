#!/usr/bin/env python3
"""Knowledge is not capability. Prove it by producing an effect the world can check.

Three rounds of this line of work measured what can be *known* about an unseen
machine -- shapes, producers, pointers, contracts. None of it ever did anything.
This closes that loop, and it does it without transferring a single fact:

  SIGNATURE   a program states the shape of its own call as a usage line:
                pygmentize [-l LEXER | -g] [-F FILTER[:options]] [-f FORMATTER]
                           [-o OUTPUTFILE] ... [INPUTFILE]
              That is a type signature. It is parsed, not learned.

  VOCABULARY  the same program renders its own vocabulary on request:
                pygmentize -L formatters   -> html, html4, ...
                pygmentize -L lexers       -> python, py, ...
              Alternatives inside a usage line (`[-l LEXER | -g]`) name the
              questions; the vocabulary answers them.

  PLAN        instantiate the signature against the vocabulary and a goal. The
              plan is a filled-in signature, not a remembered invocation.

  EFFECT      run it and check the effect on the world: the output file exists,
              is non-empty, has the expected shape, and is byte-identical on a
              repeat run. A run that produces no effect is reported as no effect.

The critical control is the **amnesiac control**: the plan for every row is
produced by a subprocess that is given the usage line, the vocabulary, and the
goal -- and nothing else. No example invocation, no prior knowledge, no memory of
the previous rows. If the plan works under that handicap, the knowledge was
derived, not recalled.

Bounded and contained: every run happens in a deleted scratch directory; inputs
are generated by this file; nothing is executed that the plan does not name.

Authority: NONE. Producer-run sandbox. Zero model calls, zero stored parameters,
no network.
"""
from __future__ import annotations

