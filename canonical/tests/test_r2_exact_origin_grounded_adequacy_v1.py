from __future__ import annotations

from hashlib import sha256
import unittest
from pathlib import Path

from canonical.runtime import general_adequate_decision_controller_v1 as controller
from canonical.runtime import p3_robust_policy_adequacy_cegar_v1 as p3
from canonical.runtime import r2_grounded_candidate_policy_frontier_v1 as frontier


ROOT = Path(__file__).resolve().parents[2]
PYPI_GOAL = (
    "Encode those exact records as MessagePack and save "
    "canonical/astra_runtime/tmp/MSGPACK_RECORDS.msgpack"
)
PYTHON_AUDIT_GOAL = (
    "Audit the Python tests with unittest and report passed failed and skipped counts."
)


class R2ExactOriginGroundedAdequacyV1Tests(unittest.TestCase):
    def test_exact_origin_autogenerated_capability_emits_authenticatable_binding(self):
        out = frontier.propose(PYPI_GOAL, repo_root=ROOT)
        self.assertTrue(out["pass"], out)
        policy_id = "BOUND_CAPABILITY_POLICY::auto.pypi.msgpack"
        self.assertIn(policy_id, out["policy_conditions"])
        self.assertIn(policy_id, out["exact_origin_adequacy_bindings"])
        binding = out["exact_origin_adequacy_bindings"][policy_id]
        ok, receipt = p3._authenticate_policy_adequacy(
            policy_id,
            out["policy_conditions"][policy_id],
            binding,
            goal_sha256=sha256(PYPI_GOAL.encode("utf-8")).hexdigest(),
        )
        self.assertTrue(ok, receipt)
        self.assertEqual(
            receipt["adequacy_source"],
            p3.EXACT_ORIGIN_BINDING_KIND,
        )

    def test_exact_origin_binding_cannot_cross_goal_identity(self):
        out = frontier.propose(PYPI_GOAL, repo_root=ROOT)
        policy_id = "BOUND_CAPABILITY_POLICY::auto.pypi.msgpack"
        binding = out["exact_origin_adequacy_bindings"][policy_id]
        ok, receipt = p3._authenticate_policy_adequacy(
            policy_id,
            out["policy_conditions"][policy_id],
            binding,
            goal_sha256=sha256(b"different goal").hexdigest(),
        )
        self.assertFalse(ok)
        self.assertIn("EXACT_ORIGIN_GOAL_BINDING_MISMATCH", receipt["reason"])

    def test_exact_origin_binding_rejects_verification_blob_drift(self):
        out = frontier.propose(PYPI_GOAL, repo_root=ROOT)
        policy_id = "BOUND_CAPABILITY_POLICY::auto.pypi.msgpack"
        binding = dict(out["exact_origin_adequacy_bindings"][policy_id])
        binding["verification_result_git_blob_sha"] = "0" * 40
        ok, receipt = p3._authenticate_policy_adequacy(
            policy_id,
            out["policy_conditions"][policy_id],
            binding,
            goal_sha256=sha256(PYPI_GOAL.encode("utf-8")).hexdigest(),
        )
        self.assertFalse(ok)
        self.assertIn("EXACT_ORIGIN_VERIFICATION_BLOB_DRIFT", receipt["reason"])

    def test_selected_grounded_capability_compiles_to_same_execution_capability(self):
        policy_id = "BOUND_CAPABILITY_POLICY::python.tests.audit.unittest"
        out = controller._compile_selected_grounded_capability_execution(
            goal=PYTHON_AUDIT_GOAL,
            selected_policy_id=policy_id,
            repo_root=ROOT,
        )
        self.assertTrue(out["pass"], out)
        self.assertEqual(
            out["execution_problem"]["selected_capability"],
            "python.tests.audit.unittest",
        )
        self.assertEqual(
            out["policy_execution_binding"]["policy_id"],
            policy_id,
        )
        self.assertFalse(
            out["policy_execution_binding"]["goal_satisfaction_authority"]
        )

    def test_unrelated_policy_cannot_hijack_compiled_execution(self):
        out = controller._compile_selected_grounded_capability_execution(
            goal=PYTHON_AUDIT_GOAL,
            selected_policy_id="BOUND_CAPABILITY_POLICY::json.query.jq",
            repo_root=ROOT,
        )
        self.assertFalse(out["pass"])
        self.assertTrue(
            str(out["status"]).startswith("FAIL_CLOSED")
            or str(out["status"]).startswith("UNRESOLVED")
        )


if __name__ == "__main__":
    unittest.main(verbosity=2)
