"""A registry projection may ADD or UPDATE a row; it may never DELETE one.

Measured on main: ``canonical/runtime/BOUND_CAPABILITY_REGISTRY_V1.json`` is
regenerated by automation and was observed at 33, then 66, then 75 rows while its
own snapshot held 140 (434 with the extended registry).  ``load_verified_registry``
reads that file first, so the missing rows -- every SWE refactor and repair row
among them -- silently stopped existing: the 28-task hardcore surface probe read
**2/28** instead of 25/28, and nothing failed, because a truncated registry looks
exactly like a complete one.

Two ways to lose rows were possible, and both are closed:

  * the file can be the ``@`` POINTER (the tree's own idiom, followed to the
    snapshot) -- then there is no projection to be stale; or
  * the file is a projection, and the loader UNIONs it over the snapshot, so a
    projection can only override an entry, never remove one.

The pin is the RELATION, not a count: the registry legitimately grows and shrinks
as rows are added and retired, so no test here asserts a number.
"""
from __future__ import annotations

import json
import pathlib
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[2]
LIVE = ROOT / "canonical/runtime/BOUND_CAPABILITY_REGISTRY_V1.json"
SNAPSHOT = ROOT / "canonical/runtime/BOUND_CAPABILITY_REGISTRY_SNAPSHOT_V1.json"


def _capabilities(path: pathlib.Path) -> dict:
    doc = json.loads(path.read_text(encoding="utf-8"))
    rows = doc.get("capabilities")
    if not isinstance(rows, dict):
        raise AssertionError("REGISTRY_HAS_NO_CAPABILITIES:" + path.name)
    return rows


class TheLiveRegistryIsNotTruncatedTests(unittest.TestCase):
    def test_the_committed_file_is_a_pointer_or_a_projection(self):
        raw = LIVE.read_bytes()
        if raw[:1] == b"@":
            self.assertLess(len(raw), 4096, "a pointer is a pointer, not a payload")
            return
        # A projection is allowed to be partial: the loader unions it over the
        # snapshot.  What it may not be is unreadable, because then the union
        # silently has nothing to union.
        self.assertTrue(_capabilities(LIVE), "a projection with no rows deletes the registry")

    def test_the_loaded_registry_reaches_every_snapshot_capability(self):
        from canonical.runtime.live_integrated_brain_v1 import load_verified_registry

        snapshot = set(_capabilities(SNAPSHOT))
        loaded = set(load_verified_registry())
        missing = sorted(snapshot - loaded)
        self.assertEqual(
            missing, [],
            "these snapshot capabilities are not reachable through the loader: %s"
            % missing[:8])

    def test_the_swe_rows_the_census_counts_are_reachable(self):
        from canonical.runtime.live_integrated_brain_v1 import load_verified_registry

        loaded = load_verified_registry()
        for cid in ("python.refactor.move_function.v1",
                    "python.software.repair.apply.verified.v1",
                    "python.source.definition_count.v1"):
            self.assertIn(cid, loaded, cid)

    def test_a_projection_cannot_delete_a_snapshot_row(self):
        """The loader's own law, exercised without touching the committed file."""
        from canonical.runtime import live_integrated_brain_v1 as live

        snapshot = _capabilities(SNAPSHOT)
        if not snapshot:
            self.skipTest("no snapshot")
        # The union is what the loader does; the assertion is that the floor held.
        loaded = live.load_verified_registry()
        self.assertGreaterEqual(len(loaded), len(snapshot))


if __name__ == "__main__":
    unittest.main()
