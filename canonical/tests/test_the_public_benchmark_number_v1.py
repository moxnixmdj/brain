"""The first public-benchmark number in 73 rounds, and its comparison.

Everything before this was measured on pages I authored. That is a closed loop (r69) and it
cannot be evidence for anything but my own consistency.

MiniWob++: 130 tasks, a codebase I did not write, goals generated by the page at run time,
rewards computed by the page. Ran all 130. No task selection by me.

    ADDRESSED rung (role + accessible name), ZERO model calls
    success 15/130 = 11.5%
    wall clock 332 s

What that number is and is not, in the same breath:
  it is real -- public tasks, published reward rule, no per-task code, no model
  it is low  -- GPT-4 scores 71.7 on this suite, WebGUM 94.2, humans ~100
  it is capped by the POLICY, not the ADDRESSING: of 130 tasks, 113 expose usable structure
  (86.9%, measured), but my goal parser understands only a handful of goal shapes. 87 of 130
  landed in one bucket called 'unknown'. The addressable ceiling was never the binding
  constraint. The parser was.

That distinction is the whole finding of the round: the ladder fixed WHERE things are. It did
nothing for WHAT the instruction means, and that is where every remaining point lives.
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))

ROOT = pathlib.Path(__file__).resolve().parents[2]
BENCH = json.loads((ROOT / "canonical/evaluation/bench/result_all_130_v1.json").read_text())
CENSUS = json.loads((ROOT / "canonical/evaluation/bench/census_130_v1.json").read_text())


def test_all_130_tasks_were_run_not_a_convenient_subset():
    assert BENCH["n"] == 130
    assert len(BENCH["tasks"]) == 130
    names = {t["task"] for t in BENCH["tasks"]}
    assert "simon-says" not in names or True   # whatever the repo ships, all of it ran


def test_the_number_is_the_number():
    win = [t for t in BENCH["tasks"] if t["done"] and isinstance(t["reward"], (int, float))
           and t["reward"] > 0]
    assert len(win) == BENCH["success"] == 15
    assert BENCH["success_rate"] == 11.5


def test_zero_model_calls_in_the_scored_path():
    """Every task in the run is tagged with the rung used. All were addressed structurally."""
    assert all(t["rung"] == "ADDRESSED" for t in BENCH["tasks"])


def test_the_binding_constraint_was_the_parser_not_the_page():
    unknown = [t for t in BENCH["tasks"] if t.get("plan") == "unknown"]
    assert len(unknown) == 87, "the parser bucket is the finding"
    addressable = [c for c in CENSUS if c.get("addressable")]
    assert len(addressable) == 113
    # the page offered structure the policy could not use
    assert len(unknown) > len(CENSUS) - len(addressable)


def test_a_lost_episode_is_not_counted_as_a_win():
    """MiniWob punishes a wrong click with reward -1 and also ends the episode. Counting
    done=True would inflate the score; the published metric is reward > 0."""
    done_but_lost = [t for t in BENCH["tasks"] if t["done"] and (t["reward"] or 0) <= 0]
    assert len(done_but_lost) == 5
    assert len([t for t in BENCH["tasks"] if t["done"]]) == 20


def test_the_comparison_is_recorded_so_it_cannot_be_quietly_dropped():
    """Numbers that make this look strong are not the ones to keep."""
    published = {"GPT-4": 71.7, "WebGUM": 94.2, "SeeAct/mobile": 66.1, "human": 100.0}
    assert max(published.values()) > BENCH["success_rate"] * 6
