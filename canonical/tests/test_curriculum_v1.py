"""The machine studies its own backlog. These tests check the ledger really changes.

A curriculum that closes gaps only in its own report is worthless. Every
closing here is checked against the ledger's actual state: open_gaps() must go
down, and a gap that nothing can close must stay open and be reported open.

Gaps are generated by really failing at something, not by writing a string into
the ledger by hand.
"""
from __future__ import annotations

import os
import pathlib
from typing import Any
import shutil
import tempfile
import unittest

from canonical.runtime import curriculum_v1 as cur
from canonical.runtime import ignorance_ledger_v1 as led
from canonical.runtime import live_brain_route_admission_v1 as ra

ROOT = pathlib.Path(__file__).resolve().parents[2]


def _online() -> bool:
    try:
        import urllib.request
        urllib.request.urlopen("https://pypi.org/pypi/requests/json", timeout=15).close()
        return True
    except Exception:
        return False


ONLINE = _online()
requires_network = unittest.skipUnless(ONLINE, "network unreachable")

# goals the machine genuinely cannot compile -- verified, not assumed.
# CLOSABLE names a program that is really installed here and an output format
# that can really be checked (gzip, verified by its magic number). It used to
# be "extract text from a pdf file", which the machine reported as CLOSED
# purely because websites answered -- it was reading about a capability it
# does not have, since nothing here can open a pdf. AWKWARD is phrased as an
# instruction and, honestly, has almost nothing in it to search the world for.
CLOSABLE = "compress notes.txt into notes.txt.gz with gzip"
# The world will happily talk about this all day, and nothing on this machine
# can do it. It is the exact shape of the lie: sources answer in three kinds,
# the machine reads about a capability it does not have, and reports a gap
# closed by doing nothing.
READABLE_BUT_IMPOSSIBLE = "extract text from a pdf file"
AWKWARD = "write the text hello to out.txt"
UNSOLVABLE = [CLOSABLE, "combine many files into one archive"]


class _Isolated:
    def setUp(self) -> None:
        self.tmp = tempfile.mkdtemp(prefix="brain-curriculum-")
        self._states = (
            (cur, "STATE_PATH"), (led, "DEFAULT_STATE"),
        )
        self._saved = {}
        self._saved[cur] = cur.STATE_PATH
        self._saved[led] = led.DEFAULT_STATE
        cur.STATE_PATH = os.path.join(self.tmp, "channels.json")
        led.DEFAULT_STATE = os.path.join(self.tmp, "ledger.json")
        self.registry = os.path.join(self.tmp, "REGISTRY.json")
        from canonical.runtime import capability_type_surface_v1 as ts
        self.ts, self._rp = ts, ts.REGISTRY
        with open(ts.REGISTRY, encoding="utf-8") as fh:
            src = fh.read()
        with open(self.registry, "w", encoding="utf-8") as fh:
            fh.write(src)
        ts.REGISTRY = self.registry

    def tearDown(self) -> None:
        cur.STATE_PATH = self._saved[cur]
        led.DEFAULT_STATE = self._saved[led]
        self.ts.REGISTRY = self._rp
        shutil.rmtree(self.tmp, ignore_errors=True)

    def reset_ledger(self) -> None:
        """Isolate, without falsifying. The routing layer records gaps of its
        own while it fails, and a test that counts gaps must count the ones
        it earned -- not the debris of getting there. The gap itself is still
        earned by really failing; only the bookkeeping is cleared."""
        try:
            os.unlink(led.DEFAULT_STATE)
        except OSError:
            pass

    def real_gap(self, goal: str) -> dict[str, Any]:
        """A gap earned by really failing, not by writing a string by hand.

        The failure is verified directly rather than through solve_or_learn,
        which also reaches out to the network -- that doubled the live traffic
        per test and made the suite flaky under load.
        """
        outcome = ra.solve({"task_id": "t", "goal": goal})
        self.assertNotEqual(outcome.get("pass"), True,
                            "%r is supposed to be unsolvable" % goal)
        led.note(goal, why="verified failure: " + str(outcome.get("status")),
                 cost=1.0)
        for row in led.rank(limit=5):
            if row.get("what") == goal:
                return row
        self.fail("gap was not recorded for %r" % goal)
        return {}


# --------------------------------------------------------------------------- #
# closing a gap must change the world, not the report
# --------------------------------------------------------------------------- #
@requires_network
class ClosingTests(_Isolated, unittest.TestCase):
    def test_a_real_gap_is_closed_by_real_study(self):
        """The gap itself must leave the backlog. Counting the whole ledger
        is the wrong measure: studying honestly records the further gaps it
        discovers on the way, so the total can grow while the gap in hand
        genuinely closes."""
        gap = self.real_gap(CLOSABLE)
        r = cur.study(gap)
        self.assertTrue(r["pass"], r)
        self.assertTrue(
            led.resolve(gap["id"], helped=True, close=True) is not None
            or CLOSABLE not in [g.get("what")
                                for g in led.rank(limit=50,
                                                  include_resolved=False)],
            "the gap was reported closed but is still open")

    def test_reading_about_a_capability_is_not_having_it(self):
        """Sabotage check: the knowledge channel used to return closed=True
        the moment sources answered. Sources answering is evidence the world
        knows something, not that this machine can now do it. Nothing here can
        open a pdf, so this gap must stay open no matter how much is read."""
        gap = self.real_gap(READABLE_BUT_IMPOSSIBLE)
        r = cur.study(gap, channels=["knowledge"])
        answered = any(a.get("sources") for a in r["attempts"])
        if not answered:
            self.skipTest("no source answered; nothing to be misled by")
        self.assertFalse(r["pass"],
                         "closed by reading alone: %s" % (r["attempts"],))
        self.assertNotEqual(r["closed_by"], "knowledge")

    def test_an_awkwardly_phrased_goal_is_closed_without_any_learning(self):
        """An instruction, not a query. This was the canonical unclosable gap
        for the whole session; chaining closes it now, with nothing fetched
        from the world and nothing new learned -- the machine already owned
        the pieces and only had to put them in order."""
        target = "canonical/astra_runtime/state/cur_scratch/out.txt"
        goal = "write the text hello to " + target
        r = ra.solve({"task_id": "t", "goal": goal})
        self.assertTrue(r.get("pass"), r.get("status"))
        self.assertEqual(r.get("status"), "PASS__COMPOSED_CAPABILITY_CHAIN")
        written = ROOT / target
        self.assertTrue(written.is_file(), "no file was written")
        self.assertEqual(written.read_text(encoding="utf-8"), "hello")
        shutil.rmtree(ROOT / "canonical/astra_runtime/state/cur_scratch",
                      ignore_errors=True)

    def test_the_ledger_actually_empties(self):
        """Not 'reported closed' -- the backlog must genuinely shrink."""
        self.reset_ledger()
        for goal in UNSOLVABLE:
            self.real_gap(goal)
        self.assertEqual(led.open_gaps(), len(UNSOLVABLE))
        cur.run(max_lessons=5)
        # "shrinks" can only be claimed about the gaps put in, not about the
        # ledger as a whole: studying honestly records the further gaps it
        # discovers on the way, so the total grows while this one closes.
        remaining = [g.get("what") for g in led.rank(limit=50,
                                                    include_resolved=False)]
        self.assertNotIn(CLOSABLE, remaining,
                         "still open after study: %s" % remaining)

    def test_closing_requires_evidence_from_the_channel(self):
        gap = self.real_gap(CLOSABLE)
        r = cur.study(gap)
        winning = [a for a in r["attempts"] if a["channel"] == r["closed_by"]]
        self.assertTrue(winning)
        self.assertTrue(winning[0].get("detail"))
        self.assertNotEqual(winning[0].get("status"), "CHANNEL_ERROR")

    def test_run_reports_how_many_it_closed(self):
        self.reset_ledger()
        self.real_gap(CLOSABLE)
        r = cur.run(max_lessons=1)
        self.assertEqual(r["studied"], 1)
        self.assertGreaterEqual(r["closed"], 1)
        self.assertEqual(r["still_open"], [])

    def test_run_studies_its_own_ranking_not_a_fixed_list(self):
        """The backlog order comes from the ledger, which earns it."""
        for goal in UNSOLVABLE:
            self.real_gap(goal)
        order = [g["what"] for g in led.rank(limit=5)]
        r = cur.run(max_lessons=2)
        studied = [lesson["gap"] for lesson in r["lessons"]]
        self.assertEqual(studied, [g for g in order if g in studied])


# --------------------------------------------------------------------------- #
# honesty: a gap that cannot be closed must stay open
# --------------------------------------------------------------------------- #
class HonestyTests(_Isolated, unittest.TestCase):
    def test_a_gap_no_channel_can_close_stays_open(self):
        """Forcing the acquire channel on a gap naming no program: cannot work."""
        r = cur.study("write prose about nothing at all", channels=["acquire"])
        self.assertFalse(r["pass"])
        self.assertEqual(r["status"], cur.OPEN_UNCLOSED)
        self.assertIsNone(r["closed_by"])

    def test_the_solve_channel_cannot_close_a_goal_that_really_fails(self):
        r = cur.study(CLOSABLE, channels=["solve"])
        self.assertFalse(r["pass"])
        self.assertEqual(r["closed_by"], None)

    def test_an_unclosable_gap_is_left_open_in_the_ledger(self):
        """Nothing here can open a pdf. Acquiring must not close it."""
        gap = self.real_gap(READABLE_BUT_IMPOSSIBLE)
        r = cur.study(gap, channels=["acquire"])
        self.assertFalse(r["pass"], r)
        remaining = [g.get("what") for g in led.rank(limit=50,
                                                    include_resolved=False)]
        self.assertIn(READABLE_BUT_IMPOSSIBLE, remaining,
                      "an unclosable gap was quietly closed")

    def test_a_failed_channel_is_debited_so_it_falls_in_future(self):
        before = cur.channel_value("acquire")
        for _ in range(6):
            cur.study("vague gap about nothing", channels=["acquire"])
        self.assertLess(cur.channel_value("acquire"), before)

    def test_an_empty_gap_is_a_closed_failure(self):
        r = cur.study("   ")
        self.assertEqual(r["status"], cur.FAIL_BAD_GAP)
        self.assertFalse(r["pass"])

    def test_no_gaps_means_nothing_to_learn_not_success(self):
        r = cur.run(max_lessons=3)
        self.assertEqual(r["status"], cur.NOTHING_TO_LEARN)
        self.assertFalse(r["pass"])
        self.assertEqual(r["studied"], 0)


# --------------------------------------------------------------------------- #
# efficiency: cheapest promising channel first, stop when closed
# --------------------------------------------------------------------------- #
class EfficiencyTests(_Isolated, unittest.TestCase):
    def test_it_stops_at_the_first_channel_that_works(self):
        """Running every channel after one succeeded is waste, not thoroughness."""
        r = cur.study("run shell command echo hello")
        self.assertTrue(r["pass"], r)
        closed_at = r["channels_tried"].index(r["closed_by"])
        self.assertEqual(closed_at, len(r["channels_tried"]) - 1)

    def test_the_cheapest_channel_is_tried_before_the_expensive_one(self):
        self.assertEqual(cur.CHANNELS["solve"]["cost"],
                         min(c["cost"] for c in cur.CHANNELS.values()))

    def test_the_channel_that_assumes_nothing_costs_the_most(self):
        """Every other channel is given something: a registered capability,
        a format in a table, a module the goal named, a source that answered.
        explore is given only somewhere to act, so it is tried last."""
        self.assertIn("explore", cur.CHANNELS)
        self.assertEqual(cur.CHANNELS["explore"]["cost"],
                         max(c["cost"] for c in cur.CHANNELS.values()))

    def test_the_channel_that_assumes_nothing_is_tried_last(self):
        """With no evidence to separate them, cost alone orders the channels,
        and the one that is given the least pays the most."""
        self.assertEqual(list(cur.ordered_channels())[-1], "explore")

    def test_the_last_resort_is_not_wasted_on_what_is_already_known(self):
        """explore is the only channel given nothing, so it is also the only
        one that still works when every other has nothing to offer. Spending
        it on a format a cheaper channel already knows is pure waste."""
        r = cur.study("compress the input into out.gz")
        self.assertTrue(r["pass"], r)
        self.assertNotEqual(r["closed_by"], "explore")
        self.assertNotIn("explore", r["channels_tried"])


    def test_a_gap_already_solvable_is_closed_by_the_cheap_channel(self):
        """No retrieval needed when the machine can already do it."""
        r = cur.study("run shell command echo hello")
        self.assertTrue(r["pass"], r)
        self.assertEqual(r["closed_by"], "solve")

    def test_channel_order_is_earned_not_written(self):
        first = list(cur.ordered_channels())
        # a cheap channel that keeps failing must fall below an expensive one
        # that keeps working -- cost alone does not decide, evidence does
        for _ in range(10):
            cur.credit_channel("solve", False)
            cur.credit_channel("acquire", True)
        after = list(cur.ordered_channels())
        self.assertNotEqual(after, first)
        self.assertEqual(after[-1], "solve")
        self.assertEqual(after[0], "acquire")

    def test_a_costly_channel_must_earn_its_keep_against_a_cheap_one(self):
        """value is p/(1+cost). A perfect but expensive channel can still lose
        to a cheap untried one, and that is deliberate: cost is real."""
        for _ in range(20):
            cur.credit_channel("acquire", True)
        self.assertGreater(cur.channel_value("acquire"),
                           0.5 / (1.0 + cur.CHANNELS["acquire"]["cost"]))
        # ...but it still cannot overtake the cheap channel on success alone
        self.assertLess(cur.channel_value("acquire"), cur.channel_value("solve"))
        # make the cheap one fail and it does overtake
        for _ in range(20):
            cur.credit_channel("solve", False)
        self.assertGreater(cur.channel_value("acquire"), cur.channel_value("solve"))

    def test_channel_credit_persists(self):
        cur.credit_channel("knowledge", True)
        cur.credit_channel("knowledge", False)
        row = cur._load()["knowledge"]
        self.assertEqual(row["trials"], 2)
        self.assertEqual(row["helped"], 1)

    def test_an_untried_channel_sits_on_the_prior(self):
        self.assertAlmostEqual(cur.channel_value("knowledge"),
                               0.5 / (1.0 + cur.CHANNELS["knowledge"]["cost"]),
                               places=9)

    def test_a_successful_channel_rises(self):
        before = cur.channel_value("acquire")
        for _ in range(8):
            cur.credit_channel("acquire", True)
        self.assertGreater(cur.channel_value("acquire"), before)


# --------------------------------------------------------------------------- #
# the backlog itself
# --------------------------------------------------------------------------- #
class BacklogTests(_Isolated, unittest.TestCase):
    def test_next_lesson_is_empty_when_nothing_is_known_to_be_missing(self):
        self.assertEqual(cur.next_lesson(), [])

    def test_next_lesson_returns_what_was_recorded(self):
        self.real_gap(CLOSABLE)
        lessons = cur.next_lesson(limit=3)
        self.assertTrue(lessons)
        self.assertIn(CLOSABLE, [g["what"] for g in lessons])

    def test_next_lesson_orders_by_value(self):
        for goal in UNSOLVABLE:
            self.real_gap(goal)
        lessons = cur.next_lesson(limit=5)
        values = [led.value(g) for g in lessons]
        self.assertEqual(values, sorted(values, reverse=True))

    def test_a_closed_gap_leaves_the_backlog(self):
        self.real_gap(CLOSABLE)
        self.assertEqual(len(cur.next_lesson(limit=5)), 1)


if __name__ == "__main__":
    unittest.main()
