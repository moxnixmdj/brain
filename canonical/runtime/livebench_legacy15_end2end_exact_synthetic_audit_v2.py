def git_blob_sha(path: Path) -> str:
    data = path.read_bytes()
    return hashlib.sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest()


def kwargs_for(iid: str, p: dict[str, Any]) -> dict[str, Any]:
    if iid == "keywords:existence":
        return {"keywords": list(p["existence"])}
    if iid == "keywords:forbidden_words":
        return {"forbidden_words": list(p["forbidden"])}
    if iid == "length_constraints:number_paragraphs":
        return {"num_paragraphs": int(p["paragraphs"])}
    if iid == "length_constraints:number_words":
        n, relation = p["words"]
        return {"num_words": int(n), "relation": str(relation)}
    if iid == "length_constraints:number_sentences":
        n, relation = p["sentences"]
        return {"num_sentences": int(n), "relation": str(relation)}
    if iid == "length_constraints:nth_paragraph_first_word":
        num, nth, first = p["nth"]
        return {
            "num_paragraphs": int(num),
            "nth_paragraph": int(nth),
            "first_word": str(first),
        }
    if iid == "detectable_content:postscript":
        return {"postscript_marker": str(p["postscript"])}
    if iid == "detectable_format:number_bullet_lists":
        return {"num_bullets": int(p["bullets"])}
    if iid == "detectable_format:multiple_sections":
        splitter, n = p["sections"]
        return {"section_spliter": str(splitter), "num_sections": int(n)}
    if iid == "startend:end_checker":
        return {"end_phrase": str(p["end"])}
    if iid in {
        "detectable_format:title",
        "detectable_format:json_format",
        "combination:two_responses",
        "combination:repeat_prompt",
        "startend:quotation",
    }:
        return {}
    raise KeyError(iid)


def render_prompt(ids: tuple[str, ...], profile: dict[str, Any], registry, reverse: bool):
    ordered = list(ids)
    if reverse:
        ordered.reverse()

    descriptions: list[str] = []
    records: list[dict[str, Any]] = []
    for iid in ordered:
        inst = registry.INSTRUCTION_DICT[iid](iid)
        kw = kwargs_for(iid, profile)
        if iid == "combination:repeat_prompt":
            desc = inst.build_description()
        else:
            desc = inst.build_description(**kw)
        descriptions.append(desc)
        records.append({"instruction_id": iid, "kwargs": dict(kw)})

    prompt = BASE_PREFIX + " " + " ".join(descriptions)
    if "combination:repeat_prompt" in ordered:
        prefix = prompt.split(REPEAT_MARKER, 1)[0]
        for record in records:
            if record["instruction_id"] == "combination:repeat_prompt":
                record["kwargs"]["prompt_to_repeat"] = prefix
                break
    return prompt, records


def exact_check(response: str, records: list[dict[str, Any]], registry):
    failed: list[str] = []
    for record in records:
        iid = record["instruction_id"]
        inst = registry.INSTRUCTION_DICT[iid](iid)
        inst.build_description(**record["kwargs"])
        try:
            ok = bool(inst.check_following(response))
        except Exception as exc:
            failed.append(iid + ":EXCEPTION:" + type(exc).__name__)
            continue
        if not ok:
            failed.append(iid)
    return not failed, failed


def audit(livebench_root: Path, max_failures: int) -> dict[str, Any]:
    legacy = livebench_root / "livebench/if_runner/instruction_following_eval"
    registry_path = legacy / "instructions_registry.py"
    instructions_path = legacy / "instructions.py"
    assert git_blob_sha(registry_path) == FROZEN_REGISTRY_BLOB
    assert git_blob_sha(instructions_path) == FROZEN_INSTRUCTIONS_BLOB

    sys.path.insert(0, str(livebench_root / "livebench/if_runner"))
    from instruction_following_eval import instructions_registry as registry

    sets = archetypes.enumerate_compatible_sets()
    assert len(sets) == EXPECTED_SET_COUNT

    total = 0
    runtime_candidate = 0
    exact_full_pass = 0
    runtime_block = 0
    exact_fail = 0
    by_archetype = defaultdict(Counter)
    by_profile = defaultdict(Counter)
    by_size = defaultdict(Counter)
    runtime_errors = Counter()
    exact_failed_ids = Counter()
    failed_shapes = Counter()
    failures = []

    for ids in sets:
        arch = archetypes.archetype(ids)
        for profile in PROFILES:
            for reverse in (False, True):
                total += 1
                tag = "reverse" if reverse else "forward"
                prompt, records = render_prompt(ids, profile, registry, reverse)
                out = witness.solve(prompt)

                if out.get("status") != "PASS_CANDIDATE_JOINT_LEGACY15_WITNESS":
                    runtime_block += 1
                    reason = str(out.get("error") or out.get("status"))
                    runtime_errors[reason] += 1
                    failed_shapes[tuple(ids)] += 1
                    for bucket in (
                        by_archetype[arch],
                        by_profile[profile["name"]],
                        by_size[len(ids)],
                    ):
                        bucket["runtime_block"] += 1
                    if len(failures) < max_failures:
                        failures.append({
                            "ids": list(ids),
                            "archetype": arch,
                            "profile": profile["name"],
                            "order": tag,
                            "stage": "runtime",
                            "reason": reason,
                        })
                    continue

                runtime_candidate += 1
                ok, failed = exact_check(str(out["response"]), records, registry)
                if ok:
                    exact_full_pass += 1
                    for bucket in (
                        by_archetype[arch],
                        by_profile[profile["name"]],
                        by_size[len(ids)],
                    ):
                        bucket["exact_full_pass"] += 1
                else:
                    exact_fail += 1
                    failed_shapes[tuple(ids)] += 1
                    for iid in failed:
                        exact_failed_ids[iid] += 1
                    for bucket in (
                        by_archetype[arch],
                        by_profile[profile["name"]],
                        by_size[len(ids)],
                    ):
                        bucket["exact_fail"] += 1
                    if len(failures) < max_failures:
                        failures.append({
                            "ids": list(ids),
                            "archetype": arch,
                            "profile": profile["name"],
                            "order": tag,
                            "stage": "exact_checker",
                            "failed_ids": failed,
                        })

    all_pass = exact_full_pass == total
    return {
        "schema": SCHEMA,
        "audit_revision": AUDIT_REVISION,
        "status": (
            "PASS__ALL_SYNTHETIC_ACTIVE15_CASES_EXACT_FULL_SCORE"
            if all_pass
            else "FAIL_CLOSED__REPAIR_LEDGER_EMITTED"
        ),
        "bindings": {
            "livebench_commit": FROZEN_LIVEBENCH_COMMIT,
            "registry_blob": FROZEN_REGISTRY_BLOB,
            "instructions_blob": FROZEN_INSTRUCTIONS_BLOB,
            "witness_schema": witness.SCHEMA,
            "archetype_schema": archetypes.SCHEMA,
        },
        "scope": {
            "active_identity_count": len(archetypes.ACTIVE_IDS),
            "compatible_identity_sets": len(sets),
            "parameter_profiles": len(PROFILES),
            "orders_per_profile": 2,
            "synthetic_cases": total,
            "terminal_rows_read": 0,
            "terminal_prompts_read": 0,
            "terminal_scores_read": 0,
        },
        "results": {
            "runtime_candidate": runtime_candidate,
            "runtime_block": runtime_block,
            "exact_full_pass": exact_full_pass,
            "exact_fail": exact_fail,
            "exact_full_pass_fraction": exact_full_pass / total,
            "failed_identity_shape_count": len(failed_shapes),
        },
        "by_archetype": {k: dict(v) for k, v in sorted(by_archetype.items())},
        "by_profile": {k: dict(v) for k, v in sorted(by_profile.items())},
        "by_size": {str(k): dict(v) for k, v in sorted(by_size.items())},
        "runtime_errors": dict(runtime_errors.most_common()),
        "exact_failed_instruction_ids": dict(exact_failed_ids.most_common()),
        "failed_identity_shapes_top": [
            {"ids": list(ids), "failures": n}
            for ids, n in failed_shapes.most_common(50)
        ],
        "failure_samples": failures,
        "hard_nonclaims": [
            "SYNTHETIC_PUBLIC_SOURCE_CONTRACT_EVIDENCE_ONLY",
            "NO_TERMINAL_CASE_CONTENT_READ",
            "NO_ACTIVE_TERMINAL_SCORE_CLAIM",
            "NO_ACCEPTANCE_FAMILY_CAPABILITY_OR_OWNERSHIP_CREDIT",
        ],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--livebench-root", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--max-failures", type=int, default=250)
    ns = ap.parse_args()

    result = audit(Path(ns.livebench_root).resolve(), ns.max_failures)
    Path(ns.output).write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "status": result["status"],
        **result["results"],
    }, sort_keys=True))
    return 0 if result["status"].startswith("PASS__") else 1


if __name__ == "__main__":
    raise SystemExit(main())
