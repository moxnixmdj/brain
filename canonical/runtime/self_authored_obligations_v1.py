#!/usr/bin/env python3
"""Work it was not given.

WHY THIS EXISTS
---------------
`creature_stakes_and_initiative_v1` gave it initiative, but every obligation on that board was
written by a person. Selecting from a menu someone else wrote is a prioritisation function. This
module is the next order of thing: the creature looks at its world, finds gaps nobody assigned, and
puts them on its own board.

WHY THAT IS DANGEROUS, AND WHAT STOPS IT
----------------------------------------
An agent that invents its own work can invent infinite work. Two failure modes, and both are
refused rather than reviewed:

  * BUSYWORK   -- a proposition that is true no matter what it does. "Be helpful." "Improve
                  quality." Unfalsifiable, so it can never be finished and never be failed. This is
                  how a self-directing agent generates an eternity of activity with no progress.
                  REFUSED__UNFALSIFIABLE.

  * SELF-SERVING CLAIMS -- a success condition weak enough that the agent's own first attempt
                  satisfies it. A check that accepts the word "verified" appearing anywhere in the
                  artifact will accept a note saying so. REFUSED__CHECK_ACCEPTS_THE_CHEAT.

So every proposal must be defended against three worlds the author does not get to choose:

    before   the gap really exists              check(before) is False
    done     the goal is actually reachable     check(done)   is True
    cheats   looking done is not being done     check(cheat)  is False for every cheat

The cheat worlds are generated by mutation of `done` -- the value moved into a note, emptied,
duplicated with one copy wrong -- which is precisely the weakness recorded in
DERIVED_INSPECTOR_KNOWN_COUNTEREXAMPLE_20261102_V1: a lexical check passes an artifact that merely
mentions the right strings.

WHAT THIS IS NOT
----------------
The value and cost it assigns to its own proposals are guesses, and nothing calibrates them. It can
only notice gaps in domains it has a reader for -- a repository it cannot parse is invisible to it.
See canonical/verification/SELF_AUTHORED_OBLIGATIONS_KNOWN_COUNTEREXAMPLE_20261102_V1.json.
"""
from __future__ import annotations

import copy
import json
from dataclasses import dataclass, field
from typing import Any, Callable, Iterable, Mapping, Sequence

from canonical.runtime.creature_stakes_and_initiative_v1 import Obligation

SCHEMA = "PROJECT_BRAIN_SELF_AUTHORED_OBLIGATIONS_V1"

ADMITTED = "ADMITTED"
REFUSED_UNFALSIFIABLE = "REFUSED__UNFALSIFIABLE"
REFUSED_ALREADY_SATISFIED = "REFUSED__ALREADY_SATISFIED"
REFUSED_NOT_SATISFIABLE = "REFUSED__NOT_SATISFIABLE"
REFUSED_ACCEPTS_CHEAT = "REFUSED__CHECK_ACCEPTS_THE_CHEAT"


@dataclass(frozen=True)
class Proposal:
    """Something it noticed and wants to do, with its own way of telling whether it is done."""

    id: str
    claim: str
    source: str
    check: Callable[[Mapping[str, Any]], bool]
    value: float = 1.0
    cost: float = 1.0
    checkable: bool = True
    predicate_spec: Mapping[str, Any] | None = None
    features: Mapping[str, Any] | None = None


def compile_predicate_spec(spec: Mapping[str, Any]) -> Callable[[Mapping[str, Any]], bool]:
    """Compile a JSON-serializable structural predicate specification into a tamper-safe check.

    Enables generic & multi-origin board obligations to survive `SIGKILL` and fresh-process
    restarts without serializing arbitrary Python bytecode.
    """
    kind = str(spec.get("kind") or "")
    ns = str(spec.get("namespace") or "")
    key = str(spec.get("key") or "")
    if kind == "slot_equals":
        expected = spec.get("expected")
        return lambda w, _ns=ns, _k=key, _exp=expected: (
            isinstance(w.get(_ns), Mapping)
            and type(w[_ns].get(_k)) is type(_exp)
            and w[_ns].get(_k) == _exp
        )
    if kind == "slot_at_least":
        threshold = float(spec.get("threshold") or 0.0)
        return lambda w, _ns=ns, _k=key, _t=threshold: (
            isinstance(w.get(_ns), Mapping)
            and isinstance(w[_ns].get(_k), (int, float))
            and not isinstance(w[_ns].get(_k), bool)
            and float(w[_ns][_k]) >= _t
        )
    if kind == "slot_is_false":
        return lambda w, _ns=ns, _k=key: (
            isinstance(w.get(_ns), Mapping) and w[_ns].get(_k) is False
        )
    raise ValueError(f"UNKNOWN_PREDICATE_SPEC_KIND:{kind}")


@dataclass
class Verdict:
    proposal_id: str
    status: str
    detail: dict[str, Any] = field(default_factory=dict)

    @property
    def admitted(self) -> bool:
        return self.status == ADMITTED


# ------------------------------------------------------------------ cheat worlds


def cheat_worlds(done: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Worlds that look done and are not.

    Generated from `done` by mutation, never by the author -- otherwise the author would be
    defining "cheating" as "whatever my check already rejects", which proves nothing.
    """
    out: list[dict[str, Any]] = []

    # 1. the value moved into a note: present, readable, and not in the place that matters.
    noted = copy.deepcopy(dict(done))
    for key, value in list(noted.items()):
        if isinstance(value, Mapping):
            inner = dict(value)
            for k, v in list(inner.items()):
                inner.pop(k)
                inner[f"note_about_{k}"] = v
            noted[key] = inner
    out.append(noted)

    # 2. present but empty.
    emptied = copy.deepcopy(dict(done))
    for key, value in list(emptied.items()):
        if isinstance(value, Mapping):
            emptied[key] = {k: "" for k in value}
    out.append(emptied)

    # 3. the value survives only in a copy while the authoritative slot is not done. A checker
    #    that scans for the string is fooled; one that reads the slot that counts is not.
    doubled = copy.deepcopy(dict(done))
    for key, value in list(doubled.items()):
        if isinstance(value, Mapping):
            inner = dict(value)
            for k, v in list(inner.items()):
                inner[k] = "<pending>"
                inner[f"{k}__copy"] = v
            doubled[key] = inner
    out.append(doubled)

    # 4. flattened to a string that merely mentions the right words.
    flattened = {k: (json.dumps(v) if isinstance(v, Mapping) else v) for k, v in done.items()}
    out.append(flattened)
    return out


# --------------------------------------------------------------------- admission


def admit(proposal: Proposal, *, before: Mapping[str, Any], done: Mapping[str, Any],
          cheats: Sequence[Mapping[str, Any]] | None = None) -> Verdict:
    """Four proofs. All of them are about the world, none about the author's sincerity."""
    cheats = cheat_worlds(done) if cheats is None else list(cheats)

    try:
        false_now = bool(proposal.check(before))
    except Exception as exc:  # a check that cannot even run on the current world
        return Verdict(proposal.id, REFUSED_NOT_SATISFIABLE,
                       {"error": type(exc).__name__, "phase": "before"})
    try:
        true_when_done = bool(proposal.check(done))
    except Exception as exc:
        return Verdict(proposal.id, REFUSED_NOT_SATISFIABLE,
                       {"error": type(exc).__name__, "phase": "done"})

    accepted_cheats: list[int] = []
    for i, cheat in enumerate(cheats):
        try:
            if proposal.check(cheat):
                accepted_cheats.append(i)
        except Exception:
            continue

    if false_now and len(accepted_cheats) == len(cheats):
        # True before it does anything, and true of every world that only pretends. It is a
        # proposition about the author's intentions, not about the world.
        return Verdict(proposal.id, REFUSED_UNFALSIFIABLE,
                       {"true_in_every_world_shown": len(cheats) + 1})
    if false_now:
        return Verdict(proposal.id, REFUSED_ALREADY_SATISFIED, {})
    if not true_when_done:
        return Verdict(proposal.id, REFUSED_NOT_SATISFIABLE, {"phase": "done"})
    if accepted_cheats:
        return Verdict(proposal.id, REFUSED_ACCEPTS_CHEAT,
                       {"accepted_cheat_indices": accepted_cheats, "of": len(cheats)})
    return Verdict(proposal.id, ADMITTED,
                   {"proved": ["gap exists", "reachable", f"rejects {len(cheats)} cheats"]})


def author(proposals: Iterable[Proposal], *, before: Mapping[str, Any],
           done: Mapping[str, Any], cheats: Sequence[Mapping[str, Any]] | None = None
           ) -> tuple[list[Obligation], list[Verdict]]:
    """Turn defended proposals into its own board. Undefended ones never reach it."""
    board: list[Obligation] = []
    verdicts: list[Verdict] = []
    for proposal in proposals:
        verdict = admit(proposal, before=before, done=done, cheats=cheats)
        verdicts.append(verdict)
        if verdict.admitted:
            board.append(Obligation(id=proposal.id, value=proposal.value, cost=proposal.cost,
                                    checkable=proposal.checkable,
                                    features=dict(proposal.features or {})))
    return board, verdicts


def metrics(verdicts: Sequence[Verdict]) -> dict[str, Any]:
    by_status: dict[str, int] = {}
    for v in verdicts:
        by_status[v.status] = by_status.get(v.status, 0) + 1
    return {"schema": SCHEMA, "proposed": len(verdicts),
            "admitted": by_status.get(ADMITTED, 0), "refusals_by_status": by_status,
            "admission_rate": round(by_status.get(ADMITTED, 0) / max(len(verdicts), 1), 4)}


# --------------------------------------------------------------- a real source


def capability_gap_proposals(capability_ids: Iterable[str],
                             inspected: Iterable[str]) -> tuple[list[Proposal], dict, dict]:
    """Gaps it can actually see in this repository: capabilities with no registered inspector.

    Its cost estimate is a rule, not a feeling: a capability with an inspected sibling sharing its
    prefix is cheaper, because the environment's checker for that family is already being read.
    """
    inspected = set(inspected)
    prefixes = {cid.rsplit(".", 1)[0] for cid in inspected}
    proposals: list[Proposal] = []
    for cid in sorted(set(capability_ids) - inspected):
        cheap = cid.rsplit(".", 1)[0] in prefixes
        spec = {"kind": "slot_equals", "namespace": "inspected", "key": cid, "expected": "verified"}
        proposals.append(Proposal(
            id=f"inspector:{cid}",
            claim=f"{cid} has a registered inspector that refuses a decoy",
            source="capability registry vs registered inspectors",
            check=compile_predicate_spec(spec),
            value=1.0,
            cost=0.5 if cheap else 1.0,
            predicate_spec=spec,
        ))
    before = {"inspected": {cid: "missing" for cid in set(capability_ids) - inspected}}
    done = {"inspected": {cid: "verified" for cid in set(capability_ids) - inspected}}
    return proposals, before, done


def naive_lexical_proposals(capability_ids: Iterable[str], inspected: Iterable[str]
                           ) -> tuple[list[Proposal], dict, dict]:
    """The criterion an author would naturally write if nobody made it defend itself: look for the
    word. Same gaps, same worlds -- the only difference is how it decides it is done."""
    inspected = set(inspected)
    missing = sorted(set(capability_ids) - inspected)
    proposals = [Proposal(id=f"inspector:{cid}", claim=f"{cid} is verified",
                          source="lexical", check=lambda w: "verified" in json.dumps(w))
                 for cid in missing]
    return (proposals, {"inspected": {cid: "missing" for cid in missing}},
            {"inspected": {cid: "verified" for cid in missing}})


def scan_repository() -> dict[str, Any]:
    """The real thing: what it finds in this tree, with nobody assigning any of it."""
    try:
        from canonical.runtime import expect_discrimination_v1 as ED
        from canonical.runtime import raw_goal_trace_acceptance_v1 as RG
        registry = ED._load_registry()
        inspectors = RG.INSPECTORS
    except Exception as exc:  # the tree changed underneath us; say so rather than guess
        return {"schema": SCHEMA, "scanned": False, "error": type(exc).__name__}

    proposals, before, done = capability_gap_proposals(registry.keys(), inspectors)
    board, verdicts = author(proposals, before=before, done=done)

    # The same gaps, judged by a criterion that only looks for the word. Reported side by side so
    # the gate is shown discriminating on the real corpus rather than only in a synthetic test.
    naive, n_before, n_done = naive_lexical_proposals(registry.keys(), inspectors)
    _, naive_verdicts = author(naive, before=n_before, done=n_done)

    out = metrics(verdicts)
    out["naive_lexical"] = metrics(naive_verdicts)
    out.update({
        "scanned": True,
        "capabilities": len(registry),
        "inspected": len(inspectors),
        "uninspected": len(proposals),
        "board_total_cost": round(sum(o.cost for o in board), 3),
        "board_cheap": sum(1 for o in board if o.cost < 1.0),
    })
    return out


def extended_cheat_worlds(done: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Stronger mutation adversary (`cheat_worlds` + comment-stuffed decoy + stringified + bool/int coercion)."""
    base = list(cheat_worlds(done))
    comment_stuffed = {"_comment": json.dumps(dict(done), sort_keys=True)}
    for k, v in done.items():
        if isinstance(v, Mapping):
            comment_stuffed[k] = {sk: f"# {sv}" for sk, sv in v.items()}
        else:
            comment_stuffed[k] = None
    wrong_type = {}
    for k, v in done.items():
        if isinstance(v, Mapping):
            wrong_type[k] = {sk: (str(sv) if isinstance(sv, (int, float, bool)) else [sv]) for sk, sv in v.items()}
        else:
            wrong_type[k] = str(v) if isinstance(v, (int, float, bool)) else [v]

    def _flip_bool_int(val: Any) -> Any:
        if val is False:
            return 0
        if val is True:
            return 1
        if type(val) is int and val == 0:
            return False
        if type(val) is int and val == 1:
            return True
        return False

    bool_coerced = {}
    for k, v in done.items():
        if isinstance(v, Mapping):
            bool_coerced[k] = {sk: _flip_bool_int(sv) for sk, sv in v.items()}
        else:
            bool_coerced[k] = _flip_bool_int(v)
    base.extend([comment_stuffed, wrong_type, bool_coerced])
    return base


def calibrate_proposal_value(
    raw_value: float,
    capability_or_family: str,
    calibration_ledger: Any = None,
) -> float:
    """Calibrate an obligation's assigned value against settled inspector-verified outcomes."""
    base = max(0.05, float(raw_value))
    if calibration_ledger is None or not hasattr(calibration_ledger, "settled_rows"):
        return round(base, 4)
    try:
        pairs = calibration_ledger.settled_rows()
    except Exception:
        return round(base, 4)
    if not pairs:
        return round(base, 4)
    fam_prefix = capability_or_family.split(":", 1)[0]
    fam_hits = [1.0 if r.get("outcome_pass") else 0.0 for r in pairs if str(r.get("capability_id") or "").startswith(fam_prefix)]
    sample = fam_hits if fam_hits else [1.0 if r.get("outcome_pass") else 0.0 for r in pairs]
    # Causal Laplace-shrunk empirical realization factor in [0.25, 1.25]
    emp_rate = (sum(sample) + 1.0) / (len(sample) + 2.0)
    return round(max(0.1, base * (0.5 + 0.75 * emp_rate)), 4)


def heterogeneous_world_proposals(
    *,
    capability_ids: Sequence[str] = (),
    inspected_ids: Sequence[str] = (),
    failing_tests: Sequence[tuple[str, str]] = (),
    numeric_chases: Sequence[Mapping[str, Any]] = (),
    open_gaps: Sequence[Mapping[str, Any]] = (),
    calibration_ledger: Any = None,
    max_inspector_gaps: int = 8,
    repair_id_prefix: str = "repair",
) -> tuple[list[Proposal], dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    """Build heterogeneous defended proposals across 4 distinct world readers + 6-cheat adversary."""
    from canonical.runtime import external_hard_slice_v1 as EHS

    proposals: list[Proposal] = []
    before: dict[str, dict[str, Any]] = {
        "inspected": {},
        "failing_tests": {},
        "numeric_targets": {},
        "open_gaps": {},
    }
    done: dict[str, dict[str, Any]] = {
        "inspected": {},
        "failing_tests": {},
        "numeric_targets": {},
        "open_gaps": {},
    }

    # Reader 1: `external_hard_slice_v1` (uninspected capabilities ranked without self-confidence)
    if capability_ids and max_inspector_gaps > 0:
        insp_map = {cid: True for cid in inspected_ids}
        if calibration_ledger is not None:
            slice_plan = EHS.select(
                capability_ids=list(capability_ids),
                ledger=calibration_ledger,
                inspectors=insp_map,
                size=max_inspector_gaps,
            )
            chosen_cids = [str(r["capability_id"]) for r in slice_plan["selected"] if not r["has_inspector"]]
        else:
            chosen_cids = sorted(set(capability_ids) - set(inspected_ids))[:max_inspector_gaps]
        prefixes = {cid.rsplit(".", 1)[0] for cid in inspected_ids if "." in cid}
        for cid in chosen_cids:
            wid = f"inspector:{cid}"
            before["inspected"][cid] = "missing"
            done["inspected"][cid] = "verified"
            cheap = ("." in cid) and (cid.rsplit(".", 1)[0] in prefixes)
            proposals.append(
                Proposal(
                    id=wid,
                    claim=f"{cid} has a mutation-falsified inspector and held-out onboarding proof",
                    source="external_hard_slice",
                    check=lambda w, _c=cid: isinstance(w.get("inspected"), Mapping) and w["inspected"].get(_c) == "verified",
                    value=calibrate_proposal_value(3.0, "inspector", calibration_ledger),
                    cost=0.5 if cheap else 1.0,
                )
            )

    # Reader 2: Workspace failing test oracle (Python + polyglot JS/TS/Rust/Go/C++)
    for rel_test, sig in failing_tests:
        wid = f"{repair_id_prefix}:{rel_test}:{sig}"
        before["failing_tests"][wid] = 1
        done["failing_tests"][wid] = 0
        proposals.append(
            Proposal(
                id=wid,
                claim=f"Workspace test {rel_test} passes under confined verification",
                source="workspace_test_oracle",
                check=lambda w, _k=wid: isinstance(w.get("failing_tests"), Mapping)
                and type(w["failing_tests"].get(_k)) is int
                and w["failing_tests"].get(_k) == 0,
                value=calibrate_proposal_value(8.0, "repair", calibration_ledger),
                cost=0.5,
            )
        )

    # Reader 3: Numeric target chases (`current_val < target_val`)
    for ch in numeric_chases:
        cid_s = str(ch.get("id") or "")
        cur_v = float(ch.get("current", 0.0))
        tgt_v = float(ch.get("target", 1.0))
        if not cid_s or cur_v >= tgt_v:
            continue
        wid = f"chase:{cid_s}"
        before["numeric_targets"][wid] = cur_v
        done["numeric_targets"][wid] = tgt_v
        proposals.append(
            Proposal(
                id=wid,
                claim=f"Numeric target {cid_s} reaches >= {tgt_v}",
                source="numeric_target_chase",
                check=lambda w, _k=wid, _t=tgt_v: isinstance(w.get("numeric_targets"), Mapping)
                and isinstance(w["numeric_targets"].get(_k), (int, float))
                and not isinstance(w["numeric_targets"].get(_k), bool)
                and float(w["numeric_targets"][_k]) >= _t,
                value=calibrate_proposal_value(6.0, "chase", calibration_ledger),
                cost=0.5,
            )
        )

    # Reader 4: Open epistemic / trajectory gaps (`ignorance_ledger_v1`)
    for idx_g, gap in enumerate(open_gaps):
        gid = str(gap.get("id") or f"g{idx_g}")
        wid = gid if gid.startswith(("gap:", "traj:")) else f"gap:{gid}"
        before["open_gaps"][wid] = True
        done["open_gaps"][wid] = False
        proposals.append(
            Proposal(
                id=wid,
                claim=f"Epistemic or trajectory gap {wid} verified closed",
                source=str(gap.get("source") or "ignorance_ledger"),
                check=lambda w, _k=wid: isinstance(w.get("open_gaps"), Mapping) and w["open_gaps"].get(_k) is False,
                value=calibrate_proposal_value(float(gap.get("value") or 3.5), "gap", calibration_ledger),
                cost=float(gap.get("cost") or 0.5),
            )
        )

    # Drop empty world namespaces so `extended_cheat_worlds` perturbs active slots cleanly
    before_clean = {k: v for k, v in before.items() if v}
    done_clean = {k: v for k, v in done.items() if v}
    cheats = extended_cheat_worlds(done_clean) if done_clean else []
    return proposals, before_clean, done_clean, cheats


class EmpiricalValueCostCalibrator:
    """Online empirical calibrator for self-authored obligation `(value, cost)` estimates.

    Closes the uncalibrated-guess counterexample in `SELF_AUTHORED_OBLIGATIONS_KNOWN_COUNTEREXAMPLE`:
    learns actual realised `(value, cost)` ratios per obligation source/family from settled work.
    """

    def __init__(self) -> None:
        self.by_source: dict[str, dict[str, float]] = {}

    def record_outcome(self, source: str, *, realised_value: float, realised_cost: float) -> None:
        key = str(source or "default")
        row = self.by_source.setdefault(key, {"n": 0.0, "sum_val": 0.0, "sum_cost": 0.0})
        row["n"] += 1.0
        row["sum_val"] += max(0.0, float(realised_value))
        row["sum_cost"] += max(0.01, float(realised_cost))

    def estimate(self, source: str, *, prior_value: float, prior_cost: float) -> tuple[float, float]:
        row = self.by_source.get(str(source or "default"))
        if not row or row["n"] <= 0.0:
            return round(float(prior_value), 4), round(max(0.05, float(prior_cost)), 4)
        n = row["n"]
        # Shrinkage blend: converges smoothly from initial prior to empirical mean
        emp_v = row["sum_val"] / n
        emp_c = row["sum_cost"] / n
        alpha = n / (n + 2.0)
        v = (1.0 - alpha) * float(prior_value) + alpha * emp_v
        c = (1.0 - alpha) * float(prior_cost) + alpha * emp_c
        return round(max(0.05, v), 4), round(max(0.05, c), 4)


class CoEvolvingCheatAdversary:
    """Monotonically growing adversarial world-mutation bank beyond fixed static mutations."""

    def __init__(self) -> None:
        self.learned_mutators: list[tuple[str, Callable[[Mapping[str, Any]], dict[str, Any]]]] = []

    def register_mutator(
        self, name: str, fn: Callable[[Mapping[str, Any]], dict[str, Any]]
    ) -> None:
        if all(existing_name != name for existing_name, _ in self.learned_mutators):
            self.learned_mutators.append((name, fn))

    def generate(self, done: Mapping[str, Any]) -> list[dict[str, Any]]:
        worlds = list(extended_cheat_worlds(done))
        # Numeric near-miss epsilon decoy (`target - 1e-3`)
        near_miss: dict[str, Any] = {}
        has_num = False
        for k, v in done.items():
            if isinstance(v, Mapping):
                inner = {}
                for sk, sv in v.items():
                    if isinstance(sv, (int, float)) and not isinstance(sv, bool):
                        inner[sk] = sv - 1
                        has_num = True
                    else:
                        inner[sk] = sv
                near_miss[k] = inner
            else:
                near_miss[k] = v
        if has_num:
            worlds.append(near_miss)

        # Nested wrapper decoy (`{"inspected": {"cap": {"value": "verified"}}}`)
        nested_wrap: dict[str, Any] = {}
        for k, v in done.items():
            if isinstance(v, Mapping):
                nested_wrap[k] = {sk: {"shadow_value": sv} for sk, sv in v.items()}
            else:
                nested_wrap[k] = {"shadow_value": v}
        worlds.append(nested_wrap)

        for _, mut_fn in self.learned_mutators:
            try:
                cand = mut_fn(done)
                if isinstance(cand, dict) and cand != dict(done):
                    worlds.append(cand)
            except Exception:
                continue
        return worlds


def discover_unparsed_workspace_obligations(
    workspace_root: Any,
    organ_graph: Any,
    *,
    calibrator: EmpiricalValueCostCalibrator | None = None,
) -> dict[str, Any]:
    """Scan unfamiliar workspace files without pre-built readers by synthesizing `PERCEPTOR` organs!

    Directly closes `SELF_AUTHORED_OBLIGATIONS_KNOWN_COUNTEREXAMPLE` ("A repository it cannot parse
    is invisible"): synthesizes verified round-trip parsers via `organ_graph`, inspects parsed
    structures for broken/pending invariants (`status != 'verified'` / `healthy == False` /
    `errors > 0`), and authors defended obligations with serializable `predicate_spec`s.
    """
    import pathlib

    root = pathlib.Path(workspace_root)
    proposals: list[Proposal] = []
    before: dict[str, dict[str, Any]] = {"synthesized_perception": {}}
    done: dict[str, dict[str, Any]] = {"synthesized_perception": {}}
    synthesized_organs: list[str] = []

    for fp in sorted(root.rglob("*")):
        if not fp.is_file() or fp.name.startswith("."):
            continue
        try:
            raw = fp.read_text(encoding="utf-8")
        except Exception:
            continue
        res = organ_graph.perceive_or_synthesize_reader(raw, format_tag=fp.suffix.lstrip(".") or "raw")
        if not res.get("ok"):
            continue
        if res.get("synthesized_new_organ"):
            synthesized_organs.append(str(res["organ_id"]))
        parsed = res["parsed"]
        rel = fp.relative_to(root).as_posix()

        # Detect actionable semantic deficits inside the newly parsed structure
        deficits: list[str] = []
        if parsed.get("kind") == "sectioned_kv":
            for sec, kv in (parsed.get("sections") or {}).items():
                if kv.get("status") in ("unverified", "missing", "broken", "failed") or kv.get("healthy") is False:
                    deficits.append(f"{rel}::{sec}")
        elif parsed.get("kind") == "table":
            for idx, row in enumerate(parsed.get("rows") or ()):
                if row.get("status") in ("unverified", "missing", "broken", "failed") or (
                    isinstance(row.get("errors"), int) and row["errors"] > 0
                ):
                    deficits.append(f"{rel}::row_{idx}")
        elif parsed.get("kind") == "sexpr":
            tree = parsed.get("tree") or []
            if "unverified" in tree or "broken" in tree:
                deficits.append(f"{rel}::sexpr_root")

        for d_key in deficits:
            wid = f"perceived_gap:{d_key}"
            spec = {
                "kind": "slot_equals",
                "namespace": "synthesized_perception",
                "key": wid,
                "expected": "resolved",
            }
            v_est, c_est = (
                calibrator.estimate("synthesized_perceptor", prior_value=4.0, prior_cost=1.0)
                if calibrator is not None
                else (4.0, 1.0)
            )
            before["synthesized_perception"][wid] = "open"
            done["synthesized_perception"][wid] = "resolved"
            proposals.append(
                Proposal(
                    id=wid,
                    claim=f"Unparsed-domain deficit {d_key} resolved and round-trip verified",
                    source="synthesized_perceptor",
                    check=compile_predicate_spec(spec),
                    value=v_est,
                    cost=c_est,
                    predicate_spec=spec,
                    features={"domain": "unparsed_artifact", "ext": fp.suffix},
                )
            )

    adversary = CoEvolvingCheatAdversary()
    cheats = adversary.generate(done) if before["synthesized_perception"] else []
    board, verdicts = (
        author(proposals, before=before, done=done, cheats=cheats)
        if proposals
        else ([], [])
    )
    return {
        "proposals": proposals,
        "board": board,
        "verdicts": verdicts,
        "before": before,
        "done": done,
        "synthesized_perceptor_organs": synthesized_organs,
    }


