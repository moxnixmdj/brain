def _constructive_witness()->dict[str,Any]:
    entries=[
      {"tool_id":"A","source_id":"S2","source_cost":2.0,"cost":4.0,"available":True,"authorized":True,"hidden_capabilities":["X"]},
      {"tool_id":"B","source_id":"S1","source_cost":1.0,"cost":1.0,"available":True,"authorized":True,"hidden_capabilities":["X","Y"]},
      {"tool_id":"C","source_id":"S2","source_cost":2.0,"cost":2.0,"available":True,"authorized":False,"hidden_capabilities":["X","Y"]},
    ]
    a=CommonFrozenToolAuthority(entries)
    structural=prove_common_authority_instance(entries,["X","Y"])
    p=a.initial_public(["X","Y"])
    actions=[]
    for _ in range(32):
        action=v5.next_action(p)
        actions.append(dict(action))
        if action["action"]=="DISCOVER":
            p["discovery_receipts"].append(a.discover(action["source_id"],["X","Y"]))
            continue
        if action["action"]=="PROBE":
            p["prior_probe_receipts"].append(
                a.probe(
                    action["tool_id"],action["capability"],
                    episode_epoch=p["decision_epoch"],
                    required_capabilities=["X","Y"],
                )
            )
            continue
        break
    return {
      "structural":structural,
      "actions":actions,
      "selected":actions[-1].get("tool_id") if actions and actions[-1].get("action")=="SELECT" else None,
      "pass":(
          structural["status"].startswith("PASS__")
          and actions
          and actions[-1]=={"action":"SELECT","tool_id":"B"}
          and {x.get("source_id") for x in actions if x.get("action")=="DISCOVER"}=={"S1","S2"}
      ),
    }


