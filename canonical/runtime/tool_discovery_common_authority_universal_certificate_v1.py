def _blob(rel:str)->str:
    data=(ROOT/rel).read_bytes()
    return hashlib.sha1(f"blob {len(data)}\0".encode()+data).hexdigest()


def _load(rel:str)->dict[str,Any]:
    x=json.loads((ROOT/rel).read_text(encoding="utf-8"))
    if not isinstance(x,dict):
        raise AssertionError(rel+":NOT_OBJECT")
    return x


def _text(rel:str)->str:
    return (ROOT/rel).read_text(encoding="utf-8")


def _find_behavior(obj:Any, behavior_id:str)->Mapping[str,Any]|None:
    if isinstance(obj,Mapping):
        if obj.get("behavior_id")==behavior_id:
            return obj
        for v in obj.values():
            got=_find_behavior(v,behavior_id)
            if got is not None:
                return got
    elif isinstance(obj,list):
        for v in obj:
            got=_find_behavior(v,behavior_id)
            if got is not None:
                return got
    return None


