def verify()->dict[str,Any]:
    drift=[p for p,w in EXPECTED.items() if _blob(p)!=w]
    if drift:
        return {
          "schema":SCHEMA,
          "status":"FAIL_CLOSED__SOURCE_BLOB_DRIFT",
          "source_blob_drift":drift,
          "universal_scope_proved":False,
          "whole_protocol_common_authority_scope_proved":False,
          "all_admissible_target_inputs_proved":False,
          "formal_completeness":False,
          "basis_kind":"UNIVERSAL_FORMAL_SCOPE_PROOF",
          "capability_credit_delta":0,"family_credit_delta":0,
          "execution_authority":False,"promotion_authority":False,
        }
    source=_source_facts()
    target=_target_facts()
    witness=_constructive_witness()
    out=prove_from_premises(source,target,witness["pass"])
    out["source_facts"]=source
    out["target_facts"]=target
    out["constructive_witness"]=witness
    out["source_blob_drift"]=[]
    return out


