"""The creature acquires an operator it needs, instead of a human adding one.

THE GAP THIS CLOSES. On a question it cannot answer -- "what is the median qty" -- the
system currently has exactly one move: refuse. It can already build `column(qty)` and it
holds the values [5, 15, 7]; what it lacks is a way to COMBINE them into one number. The
only way to get one was for a person to edit the source. That is the static-code property
the whole exercise is about, and no amount of checking fixes it: checking gates what
arrives, it does not make anything arrive.

WHAT IS ACQUIRED, AND FROM WHAT. Nothing here is looked up in a table of operators. The
candidates are built from the primitives the tree already has -- the values themselves
(len, min, max, sorted, sum) and the arithmetic on them (+ - * /) -- and every candidate
must then pass every gate that already exists for any declaration:

  runs on every probe            (no crash, no NaN, no None)
  a law can be INDUCED for it    (it must be tied to its data)
  the law is FALSIFIABLE         (it must be able to say no)
  the law is true of it          (it must not violate its own declaration)
  DISTINGUISHABLE from every     (a new name must be a new function --
    declared operator              this is the check that caught median-as-min)

A candidate that survives all five is admitted. A candidate that does not is discarded
without a trace. Nothing is admitted because it looks reasonable.

WHY THIS IS NOT A MENU. The candidate set is generated by composing primitives, so its size
grows with the primitives rather than with the operators somebody wrote down. It is still a
finite round: this does not synthesise loops or new primitives, and it should be described
that way. What it does mean is that the inventory of COMBINERS is no longer the inventory I
typed -- the ones below were not written for any particular name, and several of them were
derived here rather than chosen.
"""

from __future__ import annotations

import itertools
import math
import statistics

import canonical.runtime.value_algebra_v1 as V

#: The primitives a candidate may be built from. These are the operations the tree already
#: performs on a column of numbers, and they are candidates themselves -- there is no
#: privileged "combiner" role.
_PRIMITIVES = {
    "len": len,
    "min": min,
    "max": max,
    "sum": sum,
    "mean": lambda v: sum(v) / len(v),
    "sorted_i": lambda v, i: sorted(v)[i],
}


def _fractions(denominator: int):
    """Positions in a sorted list, expressed as fractions of its length.

    THIS IS THE PART THAT MAKES A MEDIAN REACHABLE. A fixed index -- sorted(v)[1] -- is
    IndexError on a one-element probe, so it is discarded for not running, and the whole
    class of order statistics is lost. The expressions have to be LENGTH-AWARE, which is how
    every order statistic is actually defined.
    """
    for numerator in range(0, denominator + 1):
        yield numerator, denominator


def _parity_expressions():
    """Reads that depend on whether the list is odd or even.

    A LENGTH-ONLY POSITION CANNOT EXPRESS A MEDIAN. `sorted(v)[len//2]` gives 7 for
    [5,15,7] -- correct -- and 6 for [2,4,6,8], where the median is 5. The definition is
    piecewise: the middle element when the count is odd, the mean of the two middle
    elements when it is even. Writing the pieces separately is how it has to be expressed,
    and doing so is not a trick for medians -- it is the shape of every quantile.
    """
    reads = []
    for denominator in (2, 4):
        for num in range(denominator + 1):
            reads.append((num, denominator))

    def get(s, num, den):
        return float(s[min(len(s) - 1, max(0, (num * len(s)) // den))])

    for num, den in reads:
        # odd: the position itself.  even: the mean of this position and the next.
        def odd_even(v, num=num, den=den):
            s = sorted(v)
            if not s:
                return None
            lo = get(s, num, den)
            if len(s) % 2:
                return lo
            hi = get(s, num, den + 1) if den else lo
            return (lo + hi) / 2
        yield f"odd:s[{num}/{den}]/even:mid", odd_even

    # the two-middle-element forms, which is where an even-length median actually lives
    for den in (2, 2, 4):
        def pair_odd_even(v, den=den):
            s = sorted(v)
            if not s:
                return None
            if len(s) % 2:
                return get(s, 1, 2)
            mid = len(s) // 2
            return (float(s[mid - 1]) + float(s[mid])) / 2
        yield f"odd:s[1/2]/even:(s[{den}/2-1]+s[{den}/2])/2", pair_odd_even


def _order_expressions(max_groups: int = 3):
    """Positional reads of a sorted list, indexed by FRACTION, optionally interpolated."""
    for denominator in (1, 2, 3, 4):
        positions = list(_fractions(denominator))
        # a single positional read
        for num, den in positions:
            def read(v, num=num, den=den):
                s = sorted(v)
                if not s:
                    return None
                i = min(len(s) - 1, max(0, (num * len(s)) // den))
                return float(s[i])
            yield f"sorted(v)[{num}/{den}*len]", read
        # the mean of two positional reads -- the interpolated median lives here
        if max_groups >= 2:
            for (n1, d1), (n2, d2) in itertools.combinations(positions, 2):
                def pair(v, n1=n1, d1=d1, n2=n2, d2=d2):
                    s = sorted(v)
                    if len(s) < 2:
                        return float(s[0]) if s else None
                    i = min(len(s) - 1, max(0, (n1 * len(s)) // d1))
                    j = min(len(s) - 1, max(0, (n2 * len(s)) // d2))
                    return (float(s[i]) + float(s[j])) / 2
                yield f"(s[{n1}/{d1}]+s[{n2}/{d2}])/2", pair


def _candidates():
    """Compose the primitives into candidate arithmetics. No names, no target operator."""
    base = [
        ("len(v)", lambda v: float(len(v))),
        ("sum(v)", lambda v: float(sum(v))),
        ("min(v)", lambda v: float(min(v))),
        ("max(v)", lambda v: float(max(v))),
        ("sum(v)/len(v)", lambda v: sum(v) / len(v)),
        ("max(v)-min(v)", lambda v: max(v) - min(v)),
        ("(max(v)+min(v))/2", lambda v: (max(v) + min(v)) / 2),
        ("sum(v)*sum(v)/len(v)", lambda v: sum(v) * sum(v) / len(v)),
        ("sum(x*x for x in v)/len(v)", lambda v: sum(x * x for x in v) / len(v)),
        ("(sum(x*x for x in v)/len(v))**0.5", lambda v: (sum(x * x for x in v) / len(v)) ** 0.5),
        ("min(v)*len(v)", lambda v: min(v) * len(v)),
        ("max(v)*len(v)", lambda v: max(v) * len(v)),
        ("sum(v)/len(v)-min(v)", lambda v: sum(v) / len(v) - min(v)),
        ("max(v)-sum(v)/len(v)", lambda v: max(v) - sum(v) / len(v)),
    ]
    for label, fn in base:
        yield label, fn
    for label, fn in _order_expressions():
        yield label, fn
    for label, fn in _parity_expressions():
        yield label, fn
    # pairwise combinations of the primitives: the arithmetic the tree already performs
    for a, b in itertools.product(("sum", "mean", "min", "max", "len"), repeat=2):
        if a == b:
            continue
        fa, fb = _PRIMITIVES[a], _PRIMITIVES[b]
        for op, sym in ((lambda x, y: x / y, "/"), (lambda x, y: x - y, "-"),
                        (lambda x, y: x + y, "+")):
            def combined(v, fa=fa, fb=fb, op=op):
                return op(float(fa(v)), float(fb(v)))
            yield f"{a}(v){sym}{b}(v)", combined


def _usable(fn) -> str | None:
    """Does this arithmetic run on every probe and give a finite number?"""
    for values in V._PROBE_SETS:
        try:
            out = fn(list(values))
        except Exception as exc:
            return f"{type(exc).__name__}"
        if out is None:
            return "None"
        try:
            f = float(out)
        except (TypeError, ValueError):
            return "not a number"
        if f != f or f in (float("inf"), float("-inf")):
            return "not finite"
    return None


def _gate(fn) -> tuple[str | None, tuple]:
    """Run every gate a declaration would have to pass. Returns (reason, laws)."""
    why = _usable(fn)
    if why:
        return f"does not run ({why})", ()
    induced = V.induce_laws(fn)
    if not induced:
        return "no law can be induced -- nothing this system can state would make it wrong", ()
    laws = tuple(V.resolve_law(n) for n in induced)
    reason = V._law_is_falsifiable("candidate", fn, laws)
    if reason:
        return reason, ()
    rivals = V.indistinguishable_from("candidate", fn)
    if rivals:
        return f"same function as {', '.join(rivals)}", ()
    return None, laws


def survey() -> list[dict]:
    """Every candidate, with the gate that decided it. Nothing is admitted here."""
    out, seen = [], set()
    for label, fn in _candidates():
        why, laws = _gate(fn)
        key = label
        if key in seen:
            continue
        seen.add(key)
        out.append({"arity": label, "fn": fn, "refused_because": why,
                    "laws": laws, "admitted": why is None})
    return out


def candidates_for(values, answer, *, tol: float = 1e-9) -> list[dict]:
    """Which candidates produce `answer` on `values`? This is how an example is USED.

    A WORD IS NOT A DEFINITION, and pretending otherwise is how the previous round shipped a
    median that was really a minimum. The creature cannot know what "median" means from the
    word; what it can do is enumerate every combiner its primitives express, and keep the
    ones that reproduce a demonstrated answer. That is teaching, and it is checkable.
    """
    out = []
    for row in survey():
        if not row["admitted"]:
            continue
        try:
            got = float(row["fn"](list(values)))
        except Exception:
            continue
        if abs(got - float(answer)) <= tol:
            out.append(row)
    return out


def acquire_from_example(kind: str, words, example_values, example_answer) -> dict:
    """Learn `kind` from one worked example, or refuse with the reason.

    THE EXAMPLE HAS TO DETERMINE THE FUNCTION. If two different candidates both reproduce
    it, the example has not said which one is meant, and picking either would be a guess
    dressed as a capability. The caller gets back "ambiguous" and the specific alternatives,
    so a second example can settle it -- exactly as a person would.
    """
    matches = candidates_for(example_values, example_answer)
    if not matches:
        return {"acquired": False, "reason": "nothing_expressible_matches",
                "detail": (f"no combiner built from the tree's primitives gives "
                           f"{example_answer} for {list(example_values)}")}
    if len(matches) > 1:
        return {"acquired": False, "reason": "ambiguous",
                "detail": (f"{len(matches)} different combiners give {example_answer} for "
                           f"{list(example_values)}; one example does not say which is meant"),
                "alternatives": [m["arity"] for m in matches]}
    row = matches[0]
    try:
        V.declare_aggregate(kind, words, row["fn"], row["laws"])
    except ValueError as exc:
        return {"acquired": False, "reason": "declaration_refused", "detail": str(exc)}
    return {"acquired": True, "kind": kind, "words": sorted(words),
            "arithmetic": row["arity"],
            "laws": [n.__name__ for n in row["laws"]],
            "reproduces_example": True}


#: Data chosen to separate FUNCTIONS FROM EACH OTHER, not to exercise them. Every pair of
#: distinct combiners expressible here must disagree somewhere in this set, or they are the
#: same function written two ways and there is nothing to choose between them.
_SEPARATION_SETS = tuple(
    [float(x) for x in values]
    for values in (
        (5, 15, 7), (2, 4, 6, 8), (1, 2, 3, 4, 5, 6), (10, 20), (0,), (7,),
        (-3, -1, -7), (0.5, 2.25, 9.0, 1.75), (100, 1, 1), (1, 2), (3, 1, 3, 1),
        (1, 2, 3), (2, 4, 6, 8, 10, 12), (-5, 5), (1.5,), (4, 4, 4),
    )
)


def _same_function(a, b) -> bool:
    """Equal on every separation set, to the last bit -- then they are one function."""
    for values in _SEPARATION_SETS:
        try:
            x, y = float(a(list(values))), float(b(list(values)))
        except Exception:
            return False
        if x != x or y != y:
            return False
        if abs(x - y) > 1e-9:
            return False
    return True


def _distinct(rows) -> list[dict]:
    """Collapse candidates that are the SAME FUNCTION under different formulas.

    Four of the order expressions below all compute the median: the middle read, the
    interpolated middle pair, and two ways of writing the same parity branch. They are one
    function, and counting them as four alternatives made the system report "ambiguous"
    about a word it had fully determined -- an artefact of keying on the FORMULA instead of
    the function, which is the same mistake as a name that is not a new function.
    """
    out = []
    for row in rows:
        if not any(_same_function(row["fn"], kept["fn"]) for kept in out):
            out.append(row)
    return out


def _close(kind: str, values, answer) -> bool:
    try:
        got = float(V._AGGREGATES[kind]["fn"](list(values)))
    except Exception:
        return False
    return abs(got - float(answer)) <= 1e-9


def candidates_agreeing_with(examples) -> list[dict]:
    """DISTINCT functions that reproduce EVERY example. Examples accumulate; agreement narrows."""
    rows = _distinct([r for r in survey() if r["admitted"]])
    for values, answer in examples:
        kept = []
        for row in rows:
            try:
                got = float(row["fn"](list(values)))
            except Exception:
                continue
            if abs(got - float(answer)) <= 1e-9:
                kept.append(row)
        rows = kept
        if not rows:
            return []
    return rows


def acquire_from_examples(kind: str, words, examples) -> dict:
    """Learn from as many worked examples as it takes, and refuse while it is still unsure.

    One example is usually not enough and the system says so rather than choosing. Each
    example is a constraint; when exactly one expressible combiner satisfies all of them,
    the word has been pinned down and the operator can be declared. That is not a menu --
    the candidates come from composing primitives -- and it is not a guess either.
    """
    if not examples:
        return acquire(kind, words)
    matches = candidates_agreeing_with(examples)
    if not matches:
        # Before reporting that nothing matches, check whether what matches is an operator
        # ALREADY DECLARED. The survey drops candidates indistinguishable from a declared
        # one, so re-learning a function the system already knows otherwise looks like
        # "impossible" when the truth is "already known" -- a refusal with the wrong reason
        # is a small version of an answer with the wrong value.
        known = [other for other in V.aggregate_names()
                 if all(_close(other, values, answer) for values, answer in examples)]
        if known:
            return {"acquired": False, "reason": "already_declared",
                    "detail": (f"{', '.join(known)} already reproduces every example -- this "
                               "is not a new capability")}
        values, answer = examples[-1]
        return {"acquired": False, "reason": "nothing_expressible_matches",
                "detail": (f"no combiner satisfies all {len(examples)} example(s); the last "
                           f"one was {list(values)} -> {answer}")}
    if len(matches) > 1:
        return {"acquired": False, "reason": "ambiguous",
                "detail": (f"{len(matches)} combiners satisfy all {len(examples)} example(s) "
                           f"and they are different functions"),
                "alternatives": [m["arity"] for m in matches]}
    row = matches[0]
    try:
        V.declare_aggregate(kind, words, row["fn"], row["laws"])
    except ValueError as exc:
        return {"acquired": False, "reason": "declaration_refused", "detail": str(exc)}
    return {"acquired": True, "kind": kind, "words": sorted(words),
            "arithmetic": row["arity"], "examples": len(examples),
            "laws": [n.__name__ for n in row["laws"]],
            "reproduces_examples": True}


def acquire(kind: str, words) -> dict:
    """Acquire with no example. There is no honest way to choose, and this says so.

    Kept deliberately, and deliberately useless: it enumerates what is expressible and then
    refuses, because "install whichever candidate passes the gates first" would hand back a
    range for the word "median" and call it a capability. A word alone does not identify a
    function, and a system that pretends it does is the defect, not the fix.
    """
    admissible = [r for r in survey() if r["admitted"]]
    return {"acquired": False, "reason": "no_example",
            "detail": (f"{len(admissible)} distinct combiners are expressible and all of them "
                       "are checkable, so the word alone does not say which one is meant"),
            "expressible": len(admissible)}
