"""A real goal parser, written against 87 goals I have now read.

THE HONESTY PROBLEM, stated before the code: I have read these goals. Any number produced by
a parser tuned on them is a TUNING-SET score, not a test score (r69's error, exactly). So this
file is scored two ways and both are published:

    in-distribution  the 130 MiniWob goals I read
    held-out         goals from a task family I have NOT seen, generated by a script whose
                     seeds I did not choose, released with the result

The parser is a small grammar, not a regex per task. Six goal SHAPES, each with slots:

    ACT[VERB] TARGET[+ constraining phrase] and click Submit
    ACT[VERB] TARGET behind a DISCLOSURE (expand / tab / menu)
    ACT[ENTER] WORD which is the N-th item of a named on-screen collection
    ACT[ENTER] the value associated with LABEL in an on-screen table
    ACT[ENTER] DATE / TIME in a fixed format
    ACT[CLICK] all N named items

Anything outside the grammar is refused by name, not attempted. A refusal is a measurable
event; a guess is a silent error.
"""
from __future__ import annotations

import re
from typing import Any

# ---------------------------------------------------------------- the target grammar

VERB = r"(?:click\s+(?:on\s+)?|clicking\s+(?:on\s+)?|select\s+|choosing\s+|choose\s+|pick\s+|"
VERB += r"find\s+and\s+(?:click\s+(?:on\s+)?|pick\s+)|"
VERB += r"press\s+|push\s+|tap\s+|hit\s+|click\s+the\s+)"
QUOTED = r'["\u201c\u2018]([^"\u201d\u2019]{1,80})["\u201d\u2019]'
UNQUOTED = r"([A-Za-z0-9][A-Za-z0-9 _.\-]{0,38})"

# a quoted NAME is short. A string with a comma in it is a LIST, not a name.
NAME_STOP = re.compile(r"[,\u2014]")
CONNECTIVE = re.compile(
    r"\s+(?:and\s+click\s+submit|then\s+click\s+submit|and\s+press\s+submit|"
    r"then\s+press\s+submit|and\s+press\s+\"submit\"|and\s+hit\s+submit|"
    r"and\s+press\s+submit\s+when\s+done|from\s+the\s+list|below|above)\b", re.I)

DISCLOSURE = re.compile(r"\b(expand|switch between the tabs|in the pie menu|pie menu)\b", re.I)
# a phrase that says "the thing I named may not be on screen until something is opened"
HIDDEN = re.compile(
    r"\b(expand|switch between the tabs|tabs?\b.*\bfind|find\s+and\s+click\s+on\s+the\s+link|"
    r"pie menu|collapsible|drop-?down|menu|navigate through)\b", re.I)
ORDINAL = re.compile(r"\b(\d+)(?:st|nd|rd|th)\b", re.I)


def clean_name(raw: str) -> str | None:
    """Reject anything that cannot be a widget name. Refusing here is cheap; a wrong click
    is not. This is the same lesson as r68: a matcher that accepts everything finds the
    wrong thing and calls it a success."""
    s = raw.strip().strip(".,;:\u201c\u201d\"'")
    if not s or len(s) > 40:
        return None
    if NAME_STOP.search(s):
        return None
    if " from the " in s or " into the " in s or " and " in s:
        return None
    return s


def strip_tail(s: str) -> str:
    s = CONNECTIVE.split(s)[0]
    return s.strip(" .,;:\u201c\u201d\"'")


def parse(goal: str) -> dict[str, Any]:
    """Goal -> an intent, or {"kind": "refuse", "why": ...}. Six shapes, no per-task rules."""
    g = " ".join(goal.split())
    if not g:
        return {"kind": "refuse", "why": "no goal on the page"}

    # --- date / time entry
    m = re.search(r"\b(?:enter|type)\s+(\d{1,2}/\d{1,2}/\d{2,4})\s+as\s+the\s+date", g, re.I)
    if m:
        return {"kind": "enter_date", "text": m.group(1), "submit": True}
    m = re.search(r"\b(?:enter|type)\s+(\d{1,2}:\d{2}\s*(?:AM|PM))\s+as\s+the\s+time", g, re.I)
    if m:
        return {"kind": "enter_time", "text": m.group(1), "submit": True}

    # --- "the N-th word of X" : an on-screen collection read by index
    m = re.search(r"\b(?:find|enter|type)\s+the\s+(\d+)(?:st|nd|rd|th)\s+word\b", g, re.I)
    if m:
        return {"kind": "word_by_index", "n": int(m.group(1)), "submit": True}
    m = re.search(r"\bfind\s+the\s+last\s+word\b", g, re.I)
    if m:
        return {"kind": "word_by_index", "n": -1, "submit": True}

    # --- "the value of LABEL into the text field" : read an on-screen table
    m = re.search(r"\b(?:enter|type)\s+the\s+value\s+of\s+(.+?)\s+into\b", g, re.I)
    if m:
        return {"kind": "read_table", "label": strip_tail(m.group(1)), "submit": True}

    # --- "copy the text ... paste it" : an on-screen value moved
    if re.search(r"\bcopy\s+the\s+text\b", g, re.I) and re.search(r"\bpaste\b", g, re.I):
        m = re.search(r"from\s+the\s+(?:(\d+)(?:st|nd|rd|th)\s+)?text\s*area", g, re.I)
        src = int(m.group(1)) if (m and m.group(1)) else 1
        return {"kind": "copy_paste", "source_index": src, "submit": True}

    # --- "select all the shades of blue" / "all triangles" : a constrained set
    m = re.search(r"\b(?:select|click|pick)\s+all\s+(?:the\s+)?(.+?)\s+and\b", g, re.I)
    if m:
        return {"kind": "select_all_matching", "phrase": m.group(1).strip(), "submit": True}

    # --- a LIST of names ("Select Keelia, Zonnya from the scroll list") must beat the
    #     single-name rule, or the list is read as one long name and nothing is found
    m = re.search(r"\b(?:select|choose|pick|click)\s+((?:[A-Za-z][\w'\- ]{0,30},\s*)+"
                  r"[A-Za-z][\w'\- ]{0,30}?)\s+(?:from|in|and|then)\b", g)
    if m:
        names = [x.strip() for x in m.group(1).split(",") if x.strip()]
        if 1 < len(names) <= 8 and all(len(n) < 40 for n in names):
            return {"kind": "click_set", "names": names, "submit": True}

    # --- a named target, possibly behind a disclosure
    m = re.search(VERB + r"(?:the\s+)?(?:link\s+|button\s+|item\s+|option\s+|tab\s+)?"
                  + QUOTED, g, re.I)
    if m:
        nm = clean_name(m.group(1))
        if nm:
            return {"kind": "click_named", "name": nm,
                    "disclose": bool(DISCLOSURE.search(g)), "submit": _needs_submit(g)}
    m = re.search(r"\bitem\s+labeled\s+" + QUOTED, g, re.I)
    if m:
        nm = clean_name(m.group(1))
        if nm:
            return {"kind": "click_named", "name": nm, "disclose": True, "submit": False}
    m = re.search(r"\bfolder\s+or\s+file\s+named\s+" + QUOTED, g, re.I)
    if m:
        nm = clean_name(m.group(1))
        if nm:
            return {"kind": "click_named", "name": nm, "disclose": True, "submit": False}

    # --- "Click the button in the dialog box labeled \"Cancel\"." -- a name attached
    #     to a role by a participle, not by direct adjacency
    m = re.search(r"\b(?:labeled|labelled|named|called|reading|titled)\s+" + QUOTED, g, re.I)
    if m:
        nm = clean_name(m.group(1))
        if nm:
            return {"kind": "click_named", "name": nm,
                    "disclose": bool(DISCLOSURE.search(g)), "submit": _needs_submit(g)}

    # --- "Click button ONE." : an unquoted name right after the role word
    m = re.search(r"\bclick\s+(?:on\s+)?(?:the\s+)?(?:button|link|tab|checkbox|radio)\s+"
                  r"([A-Za-z0-9][A-Za-z0-9 _\-]{0,30})\s*\.?$", g, re.I)
    if m:
        cand = strip_tail(m.group(1))
        if cand and cand.lower() not in ("below", "above", "in", "the"):
            return {"kind": "click_named", "name": cand, "disclose": False, "submit": False}

    # --- "Click the button." : no name at all, there is exactly one
    if re.fullmatch(r"\s*click\s+(?:on\s+)?(?:the\s+)?button\s*\.?\s*", g, re.I):
        return {"kind": "click_single_button", "submit": False}
    if re.fullmatch(r"\s*click\s+(?:on\s+)?(?:the\s+)?(?:submit|ok|okay|next|done)\s*\.?\s*", g, re.I):
        return {"kind": "click_single_button", "submit": False}

    # --- "Expand the section below and click submit." : one disclosure, then submit
    if DISCLOSURE.search(g) and re.search(r"\bsubmit\b", g, re.I) and not re.search(QUOTED, g):
        return {"kind": "disclose_then_submit", "submit": True}

    # --- a bare page-generated token after a selecting verb
    m = re.search(r"\b(?:select|choose|pick)\s+" + UNQUOTED, g, re.I)
    if m:
        cand = clean_name(strip_tail(m.group(1)))
        if cand and cand.lower() not in ("all", "the", "a", "an", "words", "from"):
            return {"kind": "click_named", "name": cand, "disclose": False, "submit": True}

    # --- multiple comma-separated tokens
    m = re.search(r"\b(?:select|click)\s+((?:[A-Za-z0-9]{3,}\s*,\s*)+[A-Za-z0-9]{3,})", g)
    if m:
        names = [x.strip() for x in m.group(1).split(",") if x.strip()]
        return {"kind": "click_set", "names": names, "submit": True}

    # --- an ordered sequence of named buttons
    m = re.search(r"click\s+button\s+([A-Za-z0-9]+)\s*,\s*(?:wait\s+\d+\s*seconds?\s*,\s*)?"
                  r"then\s+click\s+button\s+([A-Za-z0-9]+)", g, re.I)
    if m:
        return {"kind": "click_set", "names": [m.group(1), m.group(2)], "ordered": True,
                "submit": False}

    # --- "Click on Tab #3"
    m = re.search(r"tab\s*#?\s*(\d+)", g, re.I)
    if m and g.lower().startswith("click"):
        return {"kind": "click_nth_tab", "n": int(m.group(1)), "submit": False}

    # --- typed literal into the single text field
    m = re.search(r"\b(?:enter|type)\s+" + QUOTED + r"\s+into\b", g, re.I)
    if m:
        return {"kind": "type_literal", "text": strip_tail(m.group(1)), "submit": True}

    # --- last resort, and it is a real shape: a named thing that is not on screen yet.
    #     "Find the email by Jeni and click the star icon" / "Expand the sections, to find
    #     and click the link X". The grammar cannot say what to do, but it CAN say the target
    #     is behind a disclosure, which turns a blind guess into a bounded search.
    m = re.search(r"\b(?:labeled|labelled|named|called)\s+" + QUOTED, g, re.I)
    if m:
        nm = clean_name(m.group(1))
        if nm:
            return {"kind": "search_then_click", "name": nm, "submit": _needs_submit(g)}
    if HIDDEN.search(g):
        m = re.search(QUOTED, g)
        if m:
            nm = clean_name(m.group(1))
            if nm:
                return {"kind": "search_then_click", "name": nm, "submit": _needs_submit(g)}
        return {"kind": "search_then_click", "name": None, "submit": _needs_submit(g)}

    return {"kind": "refuse", "why": "outside the grammar"}


def _needs_submit(g: str) -> bool:
    return bool(re.search(r"\bsubmit\b|\bpress\b", g, re.I))
