class QuotientAngelicProbeInducerKernel:
    """Computes trace quotients, angelic expression synthesis, derived vocabularies,
    contrastive probe laws, and single-pass graph exploration at `K3 = 0`."""

    ENGINE_ID = "LEAPFROG_W45_QUOTIENT_ANGELIC_PROBE_INDUCER"

    def compute_trace_quotient(
        self,
        traces: Sequence[Sequence[Sequence[Tuple[Any, Any]]]],
        labels: Sequence[bool],
        *,
        max_size: int = 2,
    ) -> Dict[str, Any]:
        """Find the coarsest quotient over execution traces that separates labels with 0 collisions."""
        qt = _load_w45_module("canonical.tools.the_goal_is_a_quotient_of_the_trace_v1")
        norm_traces = [
            tuple(tuple((str(k), v) for k, v in state) for state in trace)
            for trace in traces
        ]
        norm_labels = [bool(x) for x in labels]
        generators = qt.generators_for(norm_traces)
        pool = sorted(generators.keys())[:14]
        lattice = qt.enumerate_lattice(
            generators,
            pool,
            norm_traces,
            norm_labels,
            max_size=max(1, min(3, int(max_size))),
        )
        sufficient = [row for row in lattice if int(row.get("collisions", 1)) == 0]
        best = qt.coarsest(sufficient) if sufficient else None
        return {
            "pass": best is not None,
            "engine_id": self.ENGINE_ID,
            "trace_count": len(norm_traces),
            "generator_count": len(generators),
            "lattice_evaluated": len(lattice),
            "sufficient_count": len(sufficient),
            "coarsest_quotient": best,
            "k3_model_calls": 0,
            "spend_usd": 0.0,
        }

    def angelic_force_and_synthesize(
        self,
        source: str,
        function_name: str,
        args: Sequence[Any],
        line: int,
        *,
        site_text: str = "",
        budget: int = 250,
    ) -> Dict[str, Any]:
        """Instrument function, capture live execution context at `line`, and synthesize expressions."""
        fv = _load_w45_module("canonical.tools.force_the_value_and_see_v1")
        dwi = _load_w45_module("canonical.swe_kernel.differential_witness_inversion_v1")
        inst_src, sites = fv.instrumented_source(source, function_name)
        contexts = fv.context_at(source, function_name, list(args), int(line), seconds=0.5)
        ctx = contexts[0] if contexts else {}
        chosen_site = site_text or (sites[0].get("source", "") if sites else "")
        exprs = fv.expressions_at(
            chosen_site,
            ctx,
            source,
            function_name,
            budget=max(10, int(budget)),
        ) if ctx else []
        return {
            "pass": bool(sites) and (bool(contexts) or bool(exprs)),
            "engine_id": self.ENGINE_ID,
            "function_name": function_name,
            "instrumented_site_count": len(sites),
            "instrumented_lines": len(inst_src.splitlines()),
            "captured_context_count": len(contexts),
            "captured_context_keys": sorted(ctx.keys()) if isinstance(ctx, dict) else [],
            "synthesized_expression_count": len(exprs),
            "sample_expressions": [e[0] for e in exprs[:8]],
            "differential_witness_inverter_ready": callable(
                getattr(dwi, "synthesize_live_differential_witness_repairs_in_ram", None)
            ),
            "k3_model_calls": 0,
            "spend_usd": 0.0,
        }

    def separate_vocabulary_and_explore(
        self,
        *,
        cells: Optional[Sequence[Mapping[str, Any]]] = None,
        graph: Optional[Mapping[str, Mapping[str, str]]] = None,
        start_state: str = "S0",
        goal_state: str = "GOAL",
        action_budget: int = 40,
    ) -> Dict[str, Any]:
        """Compare hand-written vs. derived vocabulary collisions and explore an unknown state graph."""
        voc = _load_w45_module("canonical.tools.the_vocabulary_must_be_computed_not_written_v1")
        probe_mod = _load_w45_module("canonical.tools.a_contrast_is_a_probe_v1")
        prov_mod = _load_w45_module("canonical.tools.an_actions_effect_is_a_provenance_map_v1")
        width_mod = _load_w45_module("canonical.tools.the_width_of_a_guard_v1")
        se = _load_w45_module("canonical.runtime.systematic_exploration_v1")

        vocab_report: Dict[str, Any] = {}
        if cells:
            norm_cells = [dict(c) for c in cells]
            vocab_report = {
                "collisions": voc.collisions(norm_cells),
                "derived_identity": voc.derived_model_can_express_identity(norm_cells),
                "hand_identity": voc.hand_model_can_express_identity(norm_cells),
            }

        explore_report: Dict[str, Any] = {}
        if graph:
            class _GraphEnv:
                def __init__(self, adj: Mapping[str, Mapping[str, str]], s0: str) -> None:
                    self._adj = adj
                    self._state = s0

                def state(self) -> str:
                    return self._state

                def reset(self) -> str:
                    self._state = start_state
                    return self._state

                def act(self, action: str) -> str:
                    nxt = self._adj.get(self._state, {}).get(action, self._state)
                    self._state = nxt
                    return nxt

                step = act

            actions = sorted({a for edges in graph.values() for a in edges.keys()})
            env = _GraphEnv(graph, start_state)
            explore_report = se.explore_to_goal(
                env,
                actions,
                is_goal=lambda s: s == goal_state,
                action_budget=max(4, int(action_budget)),
            )

        return {
            "pass": bool(explore_report.get("reached", True)) and (
                not cells or bool(vocab_report)
            ),
            "engine_id": self.ENGINE_ID,
            "vocabulary_separation": vocab_report,
            "graph_exploration": {
                "reached": bool(explore_report.get("reached", False)),
                "actions_spent": explore_report.get("actions_spent", explore_report.get("steps", 0)),
                "plan": explore_report.get("plan", []),
                "states_discovered": explore_report.get("states_discovered", 0),
            } if graph else {},
            "probe_and_guard_organs_ready": {
                "contrast_probe_justify": callable(getattr(probe_mod, "justify", None)),
                "provenance_apply_rule": callable(getattr(prov_mod, "apply_rule", None)),
                "guard_width_learn_laws": callable(getattr(width_mod, "learn_laws", None)),
            },
            "k3_model_calls": 0,
            "spend_usd": 0.0,
        }

    def run(self, payload: Optional[Mapping[str, Any]] = None) -> Dict[str, Any]:
        req = dict(payload or {})
        op = str(req.get("op") or "trace_quotient").lower()
        if op == "trace_quotient":
            return self.compute_trace_quotient(
                req.get("traces", []),
                req.get("labels", []),
                max_size=int(req.get("max_size", 2)),
            )
        if op == "angelic_force":
            return self.angelic_force_and_synthesize(
                str(req.get("source", "")),
                str(req.get("function_name", "")),
                req.get("args", ()),
                int(req.get("line", 1)),
                site_text=str(req.get("site_text", "")),
                budget=int(req.get("budget", 250)),
            )
        if op == "explore_and_vocab":
            return self.separate_vocabulary_and_explore(
                cells=req.get("cells"),
                graph=req.get("graph"),
                start_state=str(req.get("start_state", "S0")),
                goal_state=str(req.get("goal_state", "GOAL")),
                action_budget=int(req.get("action_budget", 40)),
            )
        return {"pass": False, "engine_id": self.ENGINE_ID, "error": f"UNKNOWN_OP:{op}"}


