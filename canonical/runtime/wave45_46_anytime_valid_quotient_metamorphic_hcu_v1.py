    def compute_e_process(
        self,
        heldout_outcomes: Sequence[bool],
        *,
        null_rate: float = 0.5,
        alpha: float = 0.05,
        bet_fraction: float = 0.5,
    ) -> Dict[str, Any]:
        """Compute sequential anytime-valid betting supermartingale E_t under H_0: p <= null_rate."""
        p0 = max(1e-6, min(1.0 - 1e-6, float(null_rate)))
        lam = max(0.05, min(0.95 / p0, float(bet_fraction)))
        e_val = 1.0
        max_e = 1.0
        trajectory: List[float] = []
        wins = 0
        for outcome in heldout_outcomes:
            y = 1.0 if bool(outcome) else 0.0
            if y > 0.5:
                wins += 1
            # Factor f(y) = 1 + lam * (y - p0): E_{p0}[f(Y)] = 1 exactly, and f(y) >= 0 for lam <= 1/p0
            factor = max(1e-9, 1.0 + lam * (y - p0))
            e_val *= factor
            if e_val > max_e:
                max_e = e_val
            trajectory.append(round(e_val, 6))
        threshold = 1.0 / max(1e-6, float(alpha))
        n = len(heldout_outcomes)
        return {
            "n": n,
            "wins": wins,
            "observed_rate": round(wins / n, 4) if n else 0.0,
            "null_rate": p0,
            "alpha": float(alpha),
            "ville_threshold": round(threshold, 4),
            "final_e_value": round(e_val, 6),
            "sup_e_value": round(max_e, 6),
            "anytime_valid_pass": max_e >= threshold,
            "trajectory_tail": trajectory[-6:],
        }

    def verifier_conditional_phi(
        self,
        v1_errors: Sequence[bool],
        v2_errors: Sequence[bool],
    ) -> Dict[str, Any]:
        """Compute Matthews/Pearson phi correlation between two verifiers' error indicators."""
        n = min(len(v1_errors), len(v2_errors))
        if n == 0:
            return {"n": 0, "phi": 0.0, "independent_enough": True}
        n11 = sum(1 for a, b in zip(v1_errors[:n], v2_errors[:n]) if a and b)
        n10 = sum(1 for a, b in zip(v1_errors[:n], v2_errors[:n]) if a and not b)
        n01 = sum(1 for a, b in zip(v1_errors[:n], v2_errors[:n]) if not a and b)
        n00 = n - n11 - n10 - n01
        denom = math.sqrt((n11 + n10) * (n01 + n00) * (n11 + n01) * (n10 + n00))
        phi = ((n11 * n00) - (n10 * n01)) / denom if denom > 0 else (1.0 if (n11 == n or n00 == n) else 0.0)
        return {
            "n": n,
            "phi": round(phi, 4),
            "independent_enough": phi < 0.5,
        }

